#!/bin/bash
# tests/products-abi.sh <teq N> <teq N+1> <teq 0.1.11> <out dir>: the readers of teq's products against products of
# another number (docs/TOOLING.md, "The products' number"; src/products.rs, PRODUCTS_ABI). <teq N> is a build of the
# tree, <teq N+1> the same tree built with TEQ_PRODUCTS_ABI_BUMP=1 (another target directory), <teq 0.1.11> a teq
# that writes no `abi` field (the release, or a build of its commit), whose products are of number 0. Each binary
# says its number on `--version --verbose` (`products ABI <n>`; none printed is 0).
#
# A cell per reader, writer and reading binary: a module `up` (three sources) written by the writer, read by the
# reader through one of the compiler's own commands, from one working directory (the products name it). A reader of
# the products' own number reads them, and what it builds is judged against two references of the same tree, never a
# released binary's bytes (which any change of generated code moves): its TWIN, the same cell with N and N+1 swapped
# (N+1 over N+1's products for N over N's; 0.1.11's input stays 0.1.11's), byte for byte but `teq-products.json`,
# compared without its `abi` and `identity` fields, since the number moves no generated byte; and, where the cell
# allows, a FRESH build by the same reader of the same sources: a whole build of up's and down's sources for build,
# check and products-jar, down's files byte for byte; up's three sources for own, the directory byte for byte but the
# manifest's abi and identity. removed (up/M names up.V, so no build of what it ends with compiles) and jar (down built
# over class files alone, which no whole build reads) take their twin alone. 0.1.11 is the writer of number-0
# products for the refusal and rebuild cells. PRODUCTS_ABI_PLANT=1
# is the planted control: each twin reference is taken with one byte of one class (else TASTy) file changed, and every
# read cell must then turn red (the script exits 0 when they all do and every other cell is green). A reader of another number
# refuses them with the line of src/products.rs's REFUSAL, filled and checked whole on its stderr (or a session's
# answer), and writes nothing; or, where the products are its own directory's, rebuilds: none of their entries
# kept, the directory what a fresh build of the sources given writes, byte for byte, and a downstream build that
# needs an entry not rebuilt fails. The cells:
#   build      `compiler build --target jvm --classpath <up>` of a downstream module `down`
#   check      `compiler check --classpath <up>` of `down`
#   own        `compiler build --products <up> --classpath <up>` of one of up's sources (the module's own directory)
#   removed    `compiler build --products <up> --removed <source>`, no sources
#   watch      `compiler watch --classpath <up>` over `down`, a session of each kind (`--check`, JavaScript `-o` and
#              `--split`, the JVM's `-o` directory), its first build over the reader's own products, then up published
#              again by the writer (a build answered), then by the reader again
#   session-jar  a session of each kind at 1 and 8 workers over up's products packed as a jar (N's, N+1's, 0.1.11's,
#              one whose manifest is not UTF-8): refused at its start with SESSION_REFUSAL's line whole, naming
#              `teq compiler watch` (a session reads products only from their directory), nothing written; and two
#              jars that must not be refused, read: the jar the sbt plugin's packageBin writes (up's products, the
#              manifest left out) and a jar of the stage verb's kind (an `-o` jar: class files, a resource, the
#              Teq-Products-ABI attribute in META-INF/MANIFEST.MF)
#   jar        a jar `-o` wrote (`Teq-Products-ABI` in its manifest; 0.1.11's has none) on the class path of `down`'s
#              build: a library whoever wrote it, never refused for its writer
#   products-jar  up's directory of products packaged as a jar (`teq-products.json` in it) on the class path: read
#              by its number as the directory is, another number refused by the line naming `<jar>!teq-products.json`
#   whole      `compiler build --products <up>` with <up> off `--classpath`, over a directory the writer wrote with a
#              user's files beside its products, of one source less: whatever the numbers, the old entries' files
#              it does not write again gone, the user's kept, and a downstream build that names the dropped source's
#              definition refused as scalac's separate compilation refuses it; its twin on `--classpath` where the
#              numbers differ
#   review     the review's program: a module whose body names a lean std member (`summon[Numeric[BigInt]]` behind
#              a method) written as products by N and by N+1, as its directory and packed as a jar, read by each of
#              them through the interpreter (`interp`), JavaScript (`compiler build -o`, then node) and the JVM
#              (`compiler build --target jvm`, then java): over its own number it prints 3, over the other the line
#   damaged    a manifest that is there and cannot be read or does not parse (not UTF-8, cut short past its
#              identity, empty; a jar's entry failing its CRC), in N's products as a directory and packed as a jar:
#              refused with the manifest's line by every reader N runs (build, check, the interpreter, JavaScript `-o`
#              and `--split`, the JVM's `-o`; the directory's own build and `--removed`, its manifest left as it was),
#              nothing written; in a session of each kind where the directory's manifest is damaged under it, refused,
#              then read once put back; the whole-module build over the damaged directory writes it anew (the remedy)
#   in place   a session of each kind at 1 and 8 workers over N's products directory, its files written over in
#              place with their times kept (`touch -r`, `cp -p`): N+1's (refused with the line), N's (read), N's with a
#              member renamed (down refused for want of it, the message whole), N's (read); then the same bytes
#              published again (read), after which N+1's in place are refused still
#   vc-jar     a library of value classes and their intersections (`Meters & Feet`, `Meters & Feet & Grams`) written
#              by N as products (TASTy) and as an `-o` jar (class files alone): a program built by N against the
#              products, run against the jar, prints scalac 3.8.4's `3 Feet 9` (scalac's own jar of the source and
#              client print it too): N's `-o` jar boxes and declares those methods as scalac's does
# Prints a line per cell (`products-abi: <cell> <writer> -> <reader>: <what it did>`, FAIL first where it is not
# the rule's) and the counts; exits 1 on a failure. Each command is bounded (120 s; a session's answer 30 s).
set -uo pipefail
[ $# = 4 ] || { echo "usage: tests/products-abi.sh <teq N> <teq N+1> <teq 0.1.11> <out dir>" >&2; exit 2; }
cd "$(dirname "$0")/.." || exit 1
. tests/support/jars.sh
SL=$M2/org/scala-lang/scala-library/3.8.4/scala-library-3.8.4.jar
[ -f "$SL" ] || { echo "FAIL products-abi: scala-library 3.8.4 is not in the coursier cache (incomplete validation)"; exit 1; }
template=$(sed -n 's/^pub const REFUSAL: &str = "\(.*\)";$/\1/p' src/products.rs)
[ -n "$template" ] || { echo "FAIL products-abi: src/products.rs holds no REFUSAL"; exit 1; }
session_template=$(sed -n 's/^pub const SESSION_REFUSAL: &str = "\(.*\)";$/\1/p' src/products.rs)
[ -n "$session_template" ] || { echo "FAIL products-abi: src/products.rs holds no SESSION_REFUSAL"; exit 1; }
absolute() { (cd "$(dirname "$1")" && printf '%s/%s\n' "$(pwd -P)" "$(basename "$1")"); }
mkdir -p "$4" || exit 1
out=$(cd "$4" && pwd -P)
declare -A BIN=([N]=$(absolute "$1") [N1]=$(absolute "$2") [O]=$(absolute "$3"))
declare -A ABI VERSION NAME=([N]="N" [N1]="N+1" [O]="0.1.11")
for b in N N1 O; do
  [ -x "${BIN[$b]}" ] || { echo "FAIL products-abi: ${BIN[$b]} is no binary"; exit 1; }
  VERSION[$b]=$(timeout 30 "${BIN[$b]}" --version | awk '{ print $2 }')
  ABI[$b]=$(timeout 30 "${BIN[$b]}" --version --verbose | sed -n 's/^products ABI \([0-9][0-9]*\)$/\1/p')
  ABI[$b]=${ABI[$b]:-0}
done
pass=0
fail=0
ok() { pass=$((pass + 1)); echo "products-abi: $1"; }
bad() { fail=$((fail + 1)); echo "FAIL products-abi: $1"; }
# The numbers: N's the source's (src/products.rs, PRODUCTS_ABI), N+1's one more, 0.1.11's 0.
source=$(sed -n 's/^pub const PRODUCTS_ABI: u32 = \([0-9][0-9]*\);$/\1/p' src/products.rs)
if [ "${ABI[N]}" = "$source" ] && [ "${ABI[N1]}" = $((ABI[N] + 1)) ] && [ "${ABI[O]}" = 0 ]; then
  ok "the binaries read ABI ${ABI[N]} (N, teq ${VERSION[N]}), ${ABI[N1]} (N+1, teq ${VERSION[N1]}) and ${ABI[O]} (teq ${VERSION[O]}, which prints none)"
else
  bad "the binaries' numbers: N ${ABI[N]}, N+1 ${ABI[N1]}, 0.1.11 ${ABI[O]}: N must be the source's ($source), N+1 N's plus one, 0.1.11 0"
fi

src=$out/src
rm -rf "$src" "$out/cells" "$out/ref"
mkdir -p "$src/up" "$src/down" "$out/cells" "$out/ref"
printf '%s\n' 'package up' '' 'object U:' '  def answer: Int = 42' > "$src/up/U.scala"
printf '%s\n' 'package up' '' 'object V:' '  def v: Int = 7' > "$src/up/V.scala"
printf '%s\n' 'package up' '' '@main def upMain(): Unit = println(U.answer + V.v)' > "$src/up/M.scala"
printf '%s\n' 'package down' '' '@main def run(): Unit = println(up.U.answer + up.V.v)' > "$src/down/D.scala"
ups=(up/M.scala up/U.scala up/V.scala)

# run <binary> <log> <args...>: the binary from the sources' directory, bounded, its stderr in <log>.
run() { local b=$1 log=$2; shift 2; (cd "$src" && timeout 120 "${BIN[$b]}" "$@" > "$log.out" 2> "$log"); }
# The line of REFUSAL filled: <manifest> <its number> <its writer> <reading binary> <directory or jar>.
refusal() {
  python3 - "$template" "$1" "$2" "$3" "${VERSION[$4]}" "${ABI[$4]}" "$5" <<'PY'
import sys
t, manifest, abi, writer, version, ours, place = sys.argv[1:]
for k, v in (("manifest", manifest), ("abi", abi), ("writer", writer), ("version", version), ("ours", ours), ("dir", place)):
    t = t.replace("{" + k + "}", v)
print(t)
PY
}
# The directories' files, byte for byte, but teq-products.json, whose texts are compared without `abi` and
# `identity`: nothing when they are the same, else what differs.
same_products() {
  python3 - "$1" "$2" <<'PY'
import json, os, sys
def files(d):
    out = {}
    for base, _, names in os.walk(d):
        for n in names:
            p = os.path.join(base, n)
            out[os.path.relpath(p, d)] = open(p, "rb").read()
    return out
a, b = files(sys.argv[1]), files(sys.argv[2])
diff = sorted(set(a) ^ set(b)) + sorted(p for p in set(a) & set(b) if p != "teq-products.json" and a[p] != b[p])
def manifest(text):
    m = json.loads(text)
    m.pop("identity", None)
    m.pop("abi", None)
    return m
if "teq-products.json" in a and "teq-products.json" in b and manifest(a["teq-products.json"]) != manifest(b["teq-products.json"]):
    diff.append("teq-products.json")
print(" ".join(diff))
PY
}
# The sources the manifest of a directory names, sorted, and its `abi` (absent: none).
sources_of() { python3 -c 'import json, sys; m = json.load(open(sys.argv[1])); print(" ".join(sorted({e["source"] for e in m["products"]})), m.get("abi", "none"))' "$1/teq-products.json"; }
nothing_in() { [ -z "$(find "$1" -type f 2> /dev/null)" ]; }
# A refusal: the exit code not 0, the line whole on stderr, and nothing written into <dir>.
refused() {
  local what=$1 log=$2 code=$3 line=$4 dir=$5
  if [ "$code" != 0 ] && grep -qxF -- "$line" "$log" && nothing_in "$dir"; then
    ok "$what: refused (exit $code), the line whole, nothing written"
  else
    bad "$what: not refused with the line (exit $code; wanted '$line'; stderr: $(head -c 400 "$log"); written: $(find "$dir" -type f 2> /dev/null | head -3 | tr '\n' ' '))"
  fi
}
# down's files of <dir> against <fresh>'s, byte for byte: nothing when they are, else what differs.
same_files_in() {
  python3 - "$1" "$2" <<'PY'
import os, sys
d, f = sys.argv[1:]
diff = []
for base, _, names in os.walk(d):
    for n in names:
        p = os.path.join(base, n)
        rel = os.path.relpath(p, d)
        if rel == "teq-products.json":
            continue
        q = os.path.join(f, rel)
        if not os.path.exists(q) or open(p, "rb").read() != open(q, "rb").read():
            diff.append(rel)
print(" ".join(sorted(diff)))
PY
}
# The planted control's twin: a copy of <twin> with the last byte of its first class file changed, or of its first
# TASTy file where it holds no class file (a check's products).
plant() {
  rm -rf "$1-planted" && cp -R "$1" "$1-planted"
  python3 - "$1-planted" <<'PY'
import os, sys
files = sorted(os.path.join(base, n) for base, _, names in os.walk(sys.argv[1]) for n in names)
for suffix in (".class", ".tasty"):
    for p in files:
        if p.endswith(suffix):
            b = bytearray(open(p, "rb").read())
            b[-1] ^= 1
            open(p, "wb").write(bytes(b))
            sys.exit(0)
sys.exit(1)
PY
}
# A read: exit 0, what it wrote its twin's byte for byte (the manifest without abi and identity), and, given a fresh
# build (<fresh>, <how>: `down` for down's files, `whole` for the directory), that build's too. Under the planted
# control the twin is taken changed, and the cell must be red.
read_as_twin() {
  local what=$1 log=$2 code=$3 dir=$4 twin=$5 fresh=$6 how=$7 differs fdiff=""
  if [ "${PRODUCTS_ABI_PLANT:-}" = 1 ]; then plant "$twin" || { bad "$what: no class file to plant in $twin"; return; }; twin=$twin-planted; fi
  differs=$(same_products "$dir" "$twin")
  if [ -n "$fresh" ]; then
    if [ "$how" = down ]; then fdiff=$(same_files_in "$dir" "$fresh"); else fdiff=$(same_products "$dir" "$fresh"); fi
  fi
  local green=0
  [ "$code" = 0 ] && [ -f "$dir/teq-products.json" ] && [ -z "$differs" ] && [ -z "$fdiff" ] && green=1
  if [ "${PRODUCTS_ABI_PLANT:-}" = 1 ]; then
    if [ $green = 0 ] && [ -n "$differs" ]; then ok "$what: planted twin: red, as it must be (differs in $differs)"
    else bad "$what: planted twin: still green"; fi
  elif [ $green = 1 ]; then
    ok "$what: read, its products its twin's byte for byte (the manifest without abi and identity)${fresh:+, and the fresh build ($how)}"
  else
    bad "$what: exit $code, differs from its twin in: ${differs:-nothing}, from a fresh build in: ${fdiff:-nothing} (stderr: $(head -c 400 "$log"))"
  fi
}
# up's products by <writer> into <dir>.
write_up() { run "$1" "$2.log" compiler build --target jvm --products "$2" --classpath "$SL" "${ups[@]}"; }
# The jar of up's products directory <dir>, its files in order.
pack() {
  python3 - "$1" "$2" <<'PY'
import os, sys, zipfile
d, jar = sys.argv[1:]
with zipfile.ZipFile(jar, "w") as z:
    for base, dirs, names in sorted(os.walk(d)):
        for n in sorted(names):
            p = os.path.join(base, n)
            z.write(p, os.path.relpath(p, d))
PY
}

# What each writer's products say of their number: 0.1.11's no field, N's and N+1's theirs.
for w in O N N1; do
  write_up "$w" "$out/cells/written-$w"
  got=$(sources_of "$out/cells/written-$w")
  want="up/M.scala up/U.scala up/V.scala $([ "$w" = O ] && echo none || echo "${ABI[$w]}")"
  if [ "$got" = "$want" ]; then ok "written by ${NAME[$w]}: the manifest's abi is ${got##* }"; else bad "written by ${NAME[$w]}: $got, not $want"; fi
done

# The fresh builds: each reader's whole build of up's and down's sources, and of up's for own.
f=$out/fresh
rm -rf "$f" && mkdir -p "$f"
for b in N N1; do
  run "$b" "$f/$b-build.log" compiler build --target jvm --products "$f/$b-build" --classpath "$SL" "${ups[@]}" down/D.scala
  run "$b" "$f/$b-check.log" compiler check --products "$f/$b-check" --classpath "$SL" "${ups[@]}" down/D.scala
  write_up "$b" "$f/$b-own"
  for d in build check own; do
    [ -f "$f/$b-$d/teq-products.json" ] || bad "the fresh $d of ${NAME[$b]}: no products (see $f/$b-$d*.log)"
  done
done
# twin <binary>: the binary of the same tree the cell's twin runs with (N for N+1, N+1 for N, 0.1.11 for itself).
twin() { case $1 in N) echo N1 ;; N1) echo N ;; *) echo "$1" ;; esac; }

for reader in N N1; do
  for writer in N O; do
    pair="${NAME[$writer]} -> ${NAME[$reader]}"
    same=$([ "${ABI[$writer]}" = "${ABI[$reader]}" ] && echo 1 || echo 0)
    c=$out/cells/$writer-$reader
    mkdir -p "$c"
    writer_name="teq ${VERSION[$writer]}"

    # build and check over the class path.
    for cell in build check; do
      write_up "$writer" "$c/up-$cell"
      verb=(compiler build --target jvm)
      [ $cell = check ] && verb=(compiler check)
      run "$reader" "$c/$cell.log" "${verb[@]}" --products "$c/$cell" --classpath "$c/up-$cell:$SL" down/D.scala
      code=$?
      if [ "$same" = 1 ]; then
        tw=$(twin "$writer"); tr=$(twin "$reader")
        write_up "$tw" "$c/up-$cell-twin"
        run "$tr" "$c/$cell-twin.log" "${verb[@]}" --products "$c/$cell-twin" --classpath "$c/up-$cell-twin:$SL" down/D.scala
        read_as_twin "$cell $pair" "$c/$cell.log" $code "$c/$cell" "$c/$cell-twin" "$f/$reader-$cell" down
      else refused "$cell $pair" "$c/$cell.log" $code "$(refusal "$c/up-$cell/teq-products.json" "${ABI[$writer]}" "$writer_name" "$reader" "$c/up-$cell")" "$c/$cell"; fi
    done

    # The module's own directory: one source rebuilt over it.
    write_up "$writer" "$c/own"
    run "$reader" "$c/own-1.log" compiler build --target jvm --products "$c/own" --classpath "$c/own:$SL" up/U.scala
    code=$?
    if [ "$same" = 1 ]; then
      tw=$(twin "$writer"); tr=$(twin "$reader")
      write_up "$tw" "$c/own-twin"
      run "$tr" "$c/own-twin-1.log" compiler build --target jvm --products "$c/own-twin" --classpath "$c/own-twin:$SL" up/U.scala
      read_as_twin "own $pair" "$c/own-1.log" $code "$c/own" "$c/own-twin" "$f/$reader-own" whole
    else
      run "$reader" "$c/own-fresh.log" compiler build --target jvm --products "$c/own-fresh" --classpath "$c/own-fresh:$SL" up/U.scala
      differs=$(cd "$c" && diff -r own own-fresh 2>&1 | head -3)
      run "$reader" "$c/own-down.log" compiler build --target jvm --products "$c/own-down" --classpath "$c/own:$SL" down/D.scala
      down=$?
      if [ $code = 0 ] && [ "$(sources_of "$c/own")" = "up/U.scala ${ABI[$reader]}" ] && [ -z "$differs" ] && [ $down != 0 ] && nothing_in "$c/own-down"; then
        ok "own $pair: rebuilt, no entry kept: the directory a fresh build's of up/U.scala byte for byte, and down, which needs up.V, not built over it"
      else
        bad "own $pair: exit $code, the manifest names $(sources_of "$c/own"), against a fresh build: ${differs:-the same}; down over it exits $down (stderr: $(head -c 300 "$c/own-1.log"))"
      fi
    fi

    # --removed alone.
    write_up "$writer" "$c/removed"
    cp -R "$c/removed" "$c/removed-before"
    run "$reader" "$c/removed-1.log" compiler build --target jvm --products "$c/removed" --removed up/V.scala
    code=$?
    if [ "$same" = 1 ]; then
      tw=$(twin "$writer"); tr=$(twin "$reader")
      write_up "$tw" "$c/removed-twin"
      run "$tr" "$c/removed-twin-1.log" compiler build --target jvm --products "$c/removed-twin" --removed up/V.scala
      read_as_twin "removed $pair" "$c/removed-1.log" $code "$c/removed" "$c/removed-twin" "" ""
    else
      line=$(refusal "$c/removed/teq-products.json" "${ABI[$writer]}" "$writer_name" "$reader" "$c/removed")
      if [ $code != 0 ] && grep -qxF -- "$line" "$c/removed-1.log" && diff -r "$c/removed" "$c/removed-before" > /dev/null; then
        ok "removed $pair: refused (exit $code), the line whole, the directory as it was"
      else
        bad "removed $pair: exit $code (wanted '$line'; stderr: $(head -c 400 "$c/removed-1.log"); unchanged: $(diff -rq "$c/removed" "$c/removed-before" > /dev/null && echo yes || echo no))"
      fi
    fi

    # A jar `-o` wrote: a library whatever number it names (a published jar's user cannot rebuild it), read as
    # scalac's; the attribute names the writer's number.
    run "$writer" "$c/jar-up.log" compiler build --target jvm -o "$c/up.jar" --classpath "$SL" "${ups[@]}"
    run "$reader" "$c/jar.log" compiler build --target jvm --products "$c/jar" --classpath "$c/up.jar:$SL" down/D.scala
    code=$?
    attribute=$(python3 -c 'import sys, zipfile; m = zipfile.ZipFile(sys.argv[1]).read("META-INF/MANIFEST.MF").decode(); print(next((l.split(": ", 1)[1] for l in m.split("\r\n") if l.startswith("Teq-Products-ABI: ")), "none"))' "$c/up.jar")
    tw=$(twin "$writer"); tr=$(twin "$reader")
    run "$tw" "$c/jar-up-twin.log" compiler build --target jvm -o "$c/up-twin.jar" --classpath "$SL" "${ups[@]}"
    run "$tr" "$c/jar-twin.log" compiler build --target jvm --products "$c/jar-twin" --classpath "$c/up-twin.jar:$SL" down/D.scala
    read_as_twin "jar $pair (Teq-Products-ABI: $attribute)" "$c/jar.log" $code "$c/jar" "$c/jar-twin" "" ""
    [ "$attribute" = "$([ "$writer" = O ] && echo none || echo "${ABI[$writer]}")" ] || bad "jar $pair: the jar ${NAME[$writer]} wrote names Teq-Products-ABI $attribute"

    # A directory of products packaged as a jar: read by its number as the directory is.
    write_up "$writer" "$c/up-packed"
    pack "$c/up-packed" "$c/up-products.jar"
    run "$reader" "$c/products-jar.log" compiler build --target jvm --products "$c/products-jar" --classpath "$c/up-products.jar:$SL" down/D.scala
    code=$?
    if [ "$same" = 1 ]; then
      tw=$(twin "$writer"); tr=$(twin "$reader")
      write_up "$tw" "$c/up-packed-twin"
      pack "$c/up-packed-twin" "$c/up-products-twin.jar"
      run "$tr" "$c/products-jar-twin.log" compiler build --target jvm --products "$c/products-jar-twin" --classpath "$c/up-products-twin.jar:$SL" down/D.scala
      read_as_twin "products-jar $pair" "$c/products-jar.log" $code "$c/products-jar" "$c/products-jar-twin" "$f/$reader-build" down
    else refused "products-jar $pair" "$c/products-jar.log" $code "$(refusal "$c/up-products.jar!teq-products.json" "${ABI[$writer]}" "$writer_name" "$reader" "$c/up-products.jar")" "$c/products-jar"; fi

    # The sessions, one of each kind (`--check`, JavaScript `-o` and `--split`, the JVM's `-o` directory), over the
    # directory, meeting a publication of the writer's (its first build over the reader's own products, then the
    # writer's, a build answered, then the reader's again).
    for kind in check js split jvm; do
      case $kind in
        check) how=(--check) ;;
        js) how=(-o out.js) ;;
        split) how=(--split out-split) ;;
        jvm) how=(--target jvm -o out-jvm) ;;
      esac
      w=$c/watch-$kind
      rm -rf "$w" && mkdir -p "$w"
      write_up "$reader" "$w/up"
      mkfifo "$w/cmd" "$w/ans"
      (cd "$src" && exec timeout 120 "${BIN[$reader]}" compiler watch "${how[@]/#out/$w/out}" --classpath "$w/up:$SL" down/D.scala < "$w/cmd" > "$w/ans" 2> "$w/err") &
      session=$!
      exec 3> "$w/cmd" 4< "$w/ans"
      answers=()
      for step in first writer reader; do
        case $step in
          writer) write_up "$writer" "$w/up"; echo build >&3 ;;
