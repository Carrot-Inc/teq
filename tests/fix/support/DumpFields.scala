import teq.fix.*

/** Every node's named fields through the classes' accessors, in the accessors' order, a lint each at the token
  * `marker`: the field contract of the tree (docs/FIX.md, "Tree"): each child by its kind and offsets, an empty field,
  * a missing one's exception. */
final class DumpFields extends SyntacticRule("DumpFields"):
  override def fix(using doc: SyntacticDocument): Patch =
    val at = doc.tokens.find(_.text == "marker").map(_.pos).getOrElse(doc.tree.pos)
    def show(v: Any): String = v match
      case t: Tree => t.kind + "@" + t.pos.start + "-" + t.pos.end
      case l: List[?] => l.map(show).mkString("[", ",", "]")
      case Some(x) => "Some(" + show(x) + ")"
      case None => "None"
      case x => String.valueOf(x)
    def f(name: String, v: => Any): String =
      try name + "=" + show(v)
      catch case e: NoSuchElementException => name + "=!" + e.getMessage
    def fields(t: Tree): List[String] = t match
      case t: Source => List(f("stats", t.stats))
      case t: Pkg => List(f("ref", t.ref), f("stats", t.stats))
      case t: Import => List(f("importers", t.importers))
      case t: Export => List(f("importers", t.importers))
      case t: Importer => List(f("ref", t.ref), f("importees", t.importees))
      case t: Importee.Name => List(f("name", t.name))
      case t: Importee.Rename => List(f("name", t.name), f("rename", t.rename))
      case t: Importee.Unimport => List(f("name", t.name))
      case t: Importee.Given => List(f("tpe", t.tpe))
      case t: Defn.Val => List(f("mods", t.mods), f("pats", t.pats), f("decltpe", t.decltpe), f("rhs", t.rhs))
      case t: Defn.Var => List(f("mods", t.mods), f("pats", t.pats), f("decltpe", t.decltpe), f("rhs", t.rhs))
      case t: Defn.Def => List(f("mods", t.mods), f("name", t.name), f("tparams", t.tparams), f("paramClauses", t.paramClauses), f("decltpe", t.decltpe), f("body", t.body))
      case t: Defn.Class => List(f("mods", t.mods), f("name", t.name), f("tparams", t.tparams), f("ctor", t.ctor), f("templ", t.templ))
      case t: Defn.Trait => List(f("mods", t.mods), f("name", t.name), f("tparams", t.tparams), f("templ", t.templ))
      case t: Defn.Object => List(f("mods", t.mods), f("name", t.name), f("templ", t.templ))
      case t: Defn.Enum => List(f("mods", t.mods), f("name", t.name), f("templ", t.templ))
      case t: Defn.EnumCase => List(f("mods", t.mods), f("name", t.name))
      case t: Defn.Given => List(f("mods", t.mods), f("templ", t.templ))
      case t: Defn.GivenAlias => List(f("mods", t.mods), f("body", t.body))
      case t: Defn.Type => List(f("mods", t.mods), f("name", t.name))
      case t: Decl.Val => List(f("mods", t.mods), f("pats", t.pats), f("decltpe", t.decltpe))
      case t: Decl.Var => List(f("mods", t.mods), f("pats", t.pats), f("decltpe", t.decltpe))
      case t: Decl.Def => List(f("mods", t.mods), f("name", t.name), f("tparams", t.tparams), f("paramClauses", t.paramClauses), f("decltpe", t.decltpe))
      case t: Decl.Type => List(f("mods", t.mods), f("name", t.name))
      case t: Template => List(f("inits", t.inits), f("self", t.self), f("stats", t.stats))
      case t: Init => List(f("tpe", t.tpe), f("args", t.args))
      case t: Mod.Annot => List(f("init", t.init))
      case t: Term.Select => List(f("qual", t.qual), f("name", t.name))
      case t: Term.Apply => List(f("fun", t.fun), f("args", t.args))
      case t: Term.ApplyUsing => List(f("fun", t.fun), f("args", t.args))
      case t: Term.ApplyType => List(f("fun", t.fun), f("targs", t.targs))
      case t: Term.ApplyInfix => List(f("lhs", t.lhs), f("op", t.op), f("targs", t.targs), f("args", t.args))
      case t: Term.ApplyUnary => List(f("op", t.op), f("arg", t.arg))
      case t: Term.Assign => List(f("lhs", t.lhs), f("rhs", t.rhs))
      case t: Term.Block => List(f("stats", t.stats))
      case t: Term.If => List(f("cond", t.cond), f("thenp", t.thenp), f("elsep", t.elsep))
      case t: Term.Match => List(f("expr", t.expr), f("cases", t.cases))
      case t: Term.Try => List(f("expr", t.expr), f("catchp", t.catchp), f("finallyp", t.finallyp))
      case t: Term.While => List(f("expr", t.expr), f("body", t.body))
      case t: Term.For => List(f("enums", t.enums), f("body", t.body))
      case t: Term.ForYield => List(f("enums", t.enums), f("body", t.body))
      case t: Term.Function => List(f("params", t.params), f("body", t.body))
      case t: Term.PolyFunction => List(f("tparams", t.tparams))
      case t: Term.AnonymousFunction => List(f("body", t.body))
      case t: Term.Return => List(f("expr", t.expr))
      case t: Term.Throw => List(f("expr", t.expr))
      case t: Term.New => List(f("init", t.init))
      case t: Term.NewAnonymous => List(f("templ", t.templ))
      case t: Term.Interpolate => List(f("prefix", t.prefix), f("args", t.args))
      case t: Term.Tuple => List(f("args", t.args))
      case t: Term.Ascribe => List(f("expr", t.expr), f("tpe", t.tpe))
      case t: Term.Parens => List(f("expr", t.expr))
      case t: Term.Eta => List(f("expr", t.expr))
      case t: Term.ParamClause => List(f("values", t.values), f("isImplicit", t.isImplicit), f("isUsing", t.isUsing))
      case t: Term.Param => List(f("mods", t.mods), f("name", t.name), f("decltpe", t.decltpe), f("default", t.default), f("isImplicit", t.isImplicit), f("isUsing", t.isUsing))
      case t: Case => List(f("pat", t.pat), f("cond", t.cond), f("body", t.body))
      case t: Enumerator.Generator => List(f("pat", t.pat), f("rhs", t.rhs))
      case t: Enumerator.CaseGenerator => List(f("pat", t.pat), f("rhs", t.rhs))
      case t: Enumerator.Guard => List(f("cond", t.cond))
      case t: Enumerator.Val => List(f("pat", t.pat), f("rhs", t.rhs))
      case t: Pat.Var => List(f("name", t.name))
      case t: Pat.Bind => List(f("lhs", t.lhs), f("rhs", t.rhs))
      case t: Pat.Typed => List(f("lhs", t.lhs), f("rhs", t.rhs))
      case t: Pat.Extract => List(f("fun", t.fun), f("args", t.args))
      case t: Pat.ExtractInfix => List(f("lhs", t.lhs), f("op", t.op), f("rhs", t.rhs))
      case t: Pat.Tuple => List(f("args", t.args))
      case t: Pat.Alternative => List(f("alternatives", t.alternatives))
      case t: Type.Param => List(f("mods", t.mods), f("name", t.name), f("tparams", t.tparams))
      case t: Type.Select => List(f("qual", t.qual), f("name", t.name))
      case t: Type.Apply => List(f("tpe", t.tpe), f("args", t.args))
      case t: Type.Lambda => List(f("tparams", t.tparams))
      case t: Type.PolyFunction => List(f("tparams", t.tparams))
      case t: Type.Annotate => List(f("tpe", t.tpe), f("annots", t.annots))
      case t: Name => List(f("value", t.value))
      case t: Lit => List(f("value", t.value))
      case _ => Nil
    doc.tree.collect { case t => t.kind + "@" + t.pos.start + "-" + t.pos.end + " " + fields(t).mkString(" ") }
      .map(s => Patch.lint(Diagnostic("fields", s, at))).asPatch
