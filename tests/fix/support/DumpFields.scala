import teq.fix.*

/** Every node's named fields through the classes' accessors, in the accessors' order, a lint each at the token
  * `marker`: the field contract of the tree (docs/FIX.md, "Tree"): each child by its kind and offsets, an empty field,
  * a missing one's exception. */
final class DumpFields extends SyntacticRule("DumpFields"):
  override def fix(using doc: SyntacticDocument): Patch =
    val at = doc.tokens.find(_.text == "marker").map(_.pos).getOrElse(doc.tree.pos)
    def show(v: Any): String = v match
      case t: Tree => t.kind + "@" + t.pos.start + "-" + t.pos.end
      case l: List[?] => l.map(show).mkString("[", ",", "]")
      case Some(x) => "Some(" + show(x) + ")"
      case None => "None"
      case x => String.valueOf(x)
    def f(name: String, v: => Any): String =
      try name + "=" + show(v)
      catch case e: NoSuchElementException => name + "=!" + e.getMessage
    def fields(t: Tree): List[String] = t match
      case t: Source => List(f("stats", t.stats))
      case t: Pkg => List(f("ref", t.ref), f("body", t.body))
      case t: Pkg.Body => List(f("stats", t.stats))
      case t: Import => List(f("importers", t.importers))
      case t: Export => List(f("importers", t.importers))
      case t: Importer => List(f("ref", t.ref), f("importees", t.importees))
      case t: Importee.Name => List(f("name", t.name))
      case t: Importee.Rename => List(f("name", t.name), f("rename", t.rename))
      case t: Importee.Unimport => List(f("name", t.name))
      case t: Importee.Given => List(f("tpe", t.tpe))
      case t: Defn.Val => List(f("mods", t.mods), f("pats", t.pats), f("decltpe", t.decltpe), f("rhs", t.rhs))
      case t: Defn.Var => List(f("mods", t.mods), f("pats", t.pats), f("decltpe", t.decltpe), f("rhs", t.rhs))
      case t: Defn.Def => List(f("mods", t.mods), f("name", t.name), f("paramClauseGroups", t.paramClauseGroups), f("decltpe", t.decltpe), f("body", t.body))
      case t: Defn.Class => List(f("mods", t.mods), f("name", t.name), f("tparamClause", t.tparamClause), f("ctor", t.ctor), f("templ", t.templ))
      case t: Defn.Trait => List(f("mods", t.mods), f("name", t.name), f("tparamClause", t.tparamClause), f("ctor", t.ctor), f("templ", t.templ))
      case t: Defn.Object => List(f("mods", t.mods), f("name", t.name), f("templ", t.templ))
      case t: Defn.Enum => List(f("mods", t.mods), f("name", t.name), f("tparamClause", t.tparamClause), f("ctor", t.ctor), f("templ", t.templ))
      case t: Defn.EnumCase => List(f("mods", t.mods), f("name", t.name), f("tparamClause", t.tparamClause), f("ctor", t.ctor), f("inits", t.inits))
      case t: Defn.RepeatedEnumCase => List(f("mods", t.mods), f("cases", t.cases))
      case t: Defn.Given => List(f("mods", t.mods), f("paramClauseGroups", t.paramClauseGroups), f("templ", t.templ))
      case t: Defn.GivenAlias => List(f("mods", t.mods), f("paramClauseGroups", t.paramClauseGroups), f("decltpe", t.decltpe), f("body", t.body))
      case t: Defn.Type => List(f("mods", t.mods), f("name", t.name), f("tparamClause", t.tparamClause), f("bounds", t.bounds), f("body", t.body))
      case t: Defn.ExtensionGroup => List(f("paramClauseGroup", t.paramClauseGroup), f("body", t.body))
      case t: Member.ParamClauseGroup => List(f("tparamClause", t.tparamClause), f("paramClauses", t.paramClauses))
      case t: Ctor.Primary => List(f("mods", t.mods), f("paramClauses", t.paramClauses))
      case t: Ctor.Secondary => List(f("mods", t.mods), f("name", t.name), f("paramClauses", t.paramClauses), f("body", t.body))
      case t: Ctor.Block => List(f("init", t.init), f("stats", t.stats))
      case t: Decl.Val => List(f("mods", t.mods), f("pats", t.pats), f("decltpe", t.decltpe))
      case t: Decl.Var => List(f("mods", t.mods), f("pats", t.pats), f("decltpe", t.decltpe))
      case t: Decl.Def => List(f("mods", t.mods), f("name", t.name), f("paramClauseGroups", t.paramClauseGroups), f("decltpe", t.decltpe))
      case t: Decl.Type => List(f("mods", t.mods), f("name", t.name), f("tparamClause", t.tparamClause), f("bounds", t.bounds))
      case t: Template => List(f("inits", t.inits), f("body", t.body), f("derives", t.derives))
      case t: Template.Body => List(f("selfOpt", t.selfOpt), f("stats", t.stats))
      case t: Self => List(f("name", t.name), f("decltpe", t.decltpe))
      case t: Init => List(f("tpe", t.tpe), f("argClauses", t.argClauses))
      case t: Mod.Annot => List(f("init", t.init))
      case t: Term.Select => List(f("qual", t.qual), f("name", t.name))
      case t: Term.Apply => List(f("fun", t.fun), f("argClause", t.argClause))
      case t: Term.ArgClause => List(f("values", t.values), f("mod", t.mod))
      case t: Term.ApplyType => List(f("fun", t.fun), f("targClause", t.targClause))
      case t: Term.ApplyInfix => List(f("lhs", t.lhs), f("op", t.op), f("targClause", t.targClause), f("argClause", t.argClause))
      case t: Term.Repeated => List(f("expr", t.expr))
      case t: Term.ApplyUnary => List(f("op", t.op), f("arg", t.arg))
      case t: Term.Assign => List(f("lhs", t.lhs), f("rhs", t.rhs))
      case t: Term.Block => List(f("stats", t.stats))
      case t: Term.If => List(f("cond", t.cond), f("thenp", t.thenp), f("elsep", t.elsep), f("mods", t.mods))
      case t: Term.EndMarker => List(f("name", t.name))
      case t: Type.Match => List(f("tpe", t.tpe), f("casesBlock", t.casesBlock))
      case t: Type.CasesBlock => List(f("cases", t.cases))
      case t: TypeCase => List(f("pat", t.pat), f("body", t.body))
      case t: Type.Var => List(f("name", t.name))
      case t: Type.Refine => List(f("tpe", t.tpe), f("body", t.body))
      case t: Stat.Block => List(f("stats", t.stats))
      case t: Type.Project => List(f("qual", t.qual), f("name", t.name))
      case t: Term.Match => List(f("expr", t.expr), f("casesBlock", t.casesBlock), f("mods", t.mods))
      case t: Term.SelectMatch => List(f("expr", t.expr), f("casesBlock", t.casesBlock), f("mods", t.mods))
      case t: Term.CasesBlock => List(f("cases", t.cases))
      case t: Term.PartialFunction => List(f("cases", t.cases))
      case t: Term.Try => List(f("expr", t.expr), f("catchClause", t.catchClause), f("finallyp", t.finallyp))
      case t: Term.TryWithHandler => List(f("expr", t.expr), f("catchp", t.catchp), f("finallyp", t.finallyp))
      case t: Term.While => List(f("expr", t.expr), f("body", t.body))
      case t: Term.For => List(f("enumsBlock", t.enumsBlock), f("body", t.body))
      case t: Term.EnumeratorsBlock => List(f("enums", t.enums))
      case t: Term.ForYield => List(f("enumsBlock", t.enumsBlock), f("body", t.body))
      case t: Term.FunctionTerm => List(f("paramClause", t.paramClause), f("body", t.body))
      case t: Term.SelectPostfix => List(f("qual", t.qual), f("name", t.name))
      case t: Term.PolyFunction => List(f("tparamClause", t.tparamClause), f("body", t.body))
      case t: Term.AnonymousFunction => List(f("body", t.body))
      case t: Term.Return => List(f("expr", t.expr))
      case t: Term.Throw => List(f("expr", t.expr))
      case t: Term.New => List(f("init", t.init))
      case t: Term.NewAnonymous => List(f("templ", t.templ))
      case t: Term.Interpolate => List(f("prefix", t.prefix), f("args", t.args))
      case t: Term.Tuple => List(f("args", t.args))
      case t: Term.Ascribe => List(f("expr", t.expr), f("tpe", t.tpe))
      case t: Term.Annotate => List(f("expr", t.expr), f("annots", t.annots))
      case t: Term.Eta => List(f("expr", t.expr))
      case t: Term.ParamClause => List(f("values", t.values), f("mod", t.mod))
      case t: Term.Param => List(f("mods", t.mods), f("name", t.name), f("decltpe", t.decltpe), f("default", t.default))
      case t: Case => List(f("pat", t.pat), f("cond", t.cond), f("body", t.body))
      case t: Enumerator.Generator => List(f("pat", t.pat), f("rhs", t.rhs))
      case t: Enumerator.CaseGenerator => List(f("pat", t.pat), f("rhs", t.rhs))
      case t: Enumerator.Guard => List(f("cond", t.cond))
      case t: Enumerator.Val => List(f("pat", t.pat), f("rhs", t.rhs))
      case t: Pat.Var => List(f("name", t.name))
      case t: Pat.Bind => List(f("lhs", t.lhs), f("rhs", t.rhs))
      case t: Pat.Typed => List(f("lhs", t.lhs), f("rhs", t.rhs))
      case t: Pat.Extract => List(f("fun", t.fun), f("argClause", t.argClause))
      case t: Pat.ExtractInfix => List(f("lhs", t.lhs), f("op", t.op), f("argClause", t.argClause))
      case t: Pat.ArgClause => List(f("values", t.values))
      case t: Pat.Tuple => List(f("args", t.args))
      case t: Pat.Alternative => List(f("lhs", t.lhs), f("rhs", t.rhs))
      case t: Pat.Repeated => List(f("name", t.name))
      case t: Pat.Given => List(f("tpe", t.tpe))
      case t: Type.Param => List(f("mods", t.mods), f("name", t.name), f("tparamClause", t.tparamClause), f("bounds", t.bounds))
      case t: Type.ParamClause => List(f("values", t.values))
      case t: Type.Bounds => List(f("lo", t.lo), f("hi", t.hi), f("context", t.context))
      case t: Type.Function => List(f("paramClause", t.paramClause), f("res", t.res))
      case t: Type.ContextFunction => List(f("paramClause", t.paramClause), f("res", t.res))
      case t: Type.FuncParamClause => List(f("values", t.values))
      case t: Type.Select => List(f("qual", t.qual), f("name", t.name))
      case t: Type.Apply => List(f("tpe", t.tpe), f("argClause", t.argClause))
      case t: Type.ArgClause => List(f("values", t.values))
      case t: Type.ApplyInfix => List(f("lhs", t.lhs), f("op", t.op), f("rhs", t.rhs))
      case t: Type.Lambda => List(f("tparamClause", t.tparamClause))
      case t: Type.PolyFunction => List(f("tparamClause", t.tparamClause))
      case t: Type.Annotate => List(f("tpe", t.tpe), f("annots", t.annots))
      case t: Name => List(f("value", t.value))
      case t: Lit => List(f("value", t.value))
      case _ => Nil
    doc.tree.collect { case t => t.kind + "@" + t.pos.start + "-" + t.pos.end + " " + fields(t).mkString(" ") }
      .map(s => Patch.lint(Diagnostic("fields", s, at))).asPatch
