# The tests a run owes are the export's (`Locks.testUnits`): over an export with alpha's and beta's test configurations,
# tests.json alpha's alone, and a record of beta's test build failing, a run that omits beta fails, judged and recorded;
# one where beta's tests end with nothing to run has its build's item gone.
cp "$work/checkout/target/teq/teq.lock" "$work/lock.kept"
