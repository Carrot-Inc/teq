  '  beta:' '    configurations:' '      test:' '        frameworks:' '          - arguments: []' '            class: munit.Framework' '        sources:' '          - beta/test' > "$work/checkout/target/teq/teq.lock"
mkdir -p "$work/omit" && cp bench/lila/pin.json "$work/omit/"
printf '%s\n' '{"suites": {"lila.a.OneTest": {"project": "alpha", "cases": ["adds", "subtracts: twice"]}, "lila.a.TwoTest": {"project": "alpha", "cases": ["parses"]}}}' > "$work/omit/tests.json"
alpha_run='[success] lila.a.OneTest adds
[success] lila.a.OneTest subtracts: twice
[success] lila.a.TwoTest parses
alpha/test: 2 suites, 3 passed, 0 failed in 10 ms (built in 5 ms)'
{ printf '%s\n' "$alpha_run"; printf '%s\n' 'beta/B.scala:1:1: error: Not found: b' 'b' '^' 'beta/test: 1 error'; } | transcript
echo 1 > "$work/exit"
verb "$work/omit" baseline
expect "a baseline of alpha's tests and beta's failed build" pass "$work/omit"
grep -q -F 'beta/test beta/B.scala:1:1: error: Not found: b' "$work/omit/deviations.json" && pass=$((pass + 1)) || { echo "FAIL beta's failed build is no item of the baseline"; fail=$((fail + 1)); }
rm -f "$work/exit"
printf '%s\n' "$alpha_run" | transcript
cp "$work/omit/deviations.json" "$work/deviations.kept"
verb "$work/omit"
code=$?
verb "$work/omit" record
code2=$?
[ $code != 0 ] && [ $code2 != 0 ] && grep -q "beta: the export holds its tests, and the run shows neither" "$work/verb.log" && cmp -s "$work/omit/deviations.json" "$work/deviations.kept" && pass=$((pass + 1)) ||
  { echo "FAIL a run omitting beta's tests: exits $code and $code2, or the record changed: $(tail -3 "$work/verb.log")"; fail=$((fail + 1)); }
{ printf '%s\n' "$alpha_run"; echo 'beta/test: no suite to run'; } | transcript
verb "$work/omit"
expect "beta's tests ending with nothing to run" pass "$work/omit"
grep -q "gone 1 of the record's 1" "$work/verb.log" && pass=$((pass + 1)) || { echo "FAIL beta's build's item not gone: $(tail -3 "$work/verb.log")"; fail=$((fail + 1)); }
# A diagnostic on teq's stderr before beta's end with nothing run is the compiler's without its count, whatever run
