printf '%s\n' "alpha	lila.a.OneTest	test adds	Success	" "alpha	lila.a.OneTest	test subtracts: twice	Success	" "alpha	lila.a.TwoTest	test parses	Success	" \
  "beta	lila.b.ThreeTest	test renders	Error	" > "$work/events.new" && mv "$work/events.new" "$work/events-override.txt"
cp "$work/blocked/deviations.json" "$work/deviations.kept"
expect "a blocked project's case run as an error" fail "$work/blocked"
grep -q "beta: a build of its failed and 1 of its cases ran: an execution its build's failure contradicts" "$work/verb.log" && grep -q "beta: lila.b.ThreeTest: renders: Error (tests.json: Success)" "$work/verb.log" && pass=$((pass + 1)) ||
  { echo "FAIL the executed case under a blocked build: not a contradiction and an item: $(tail -4 "$work/verb.log")"; fail=$((fail + 1)); }
verb "$work/blocked" record
cmp -s "$work/blocked/deviations.json" "$work/deviations.kept" && pass=$((pass + 1)) || { echo "FAIL the executed case under a blocked build: its --record changed the record"; fail=$((fail + 1)); }
rm -f "$work/events-override.txt" "$work/exit"
# The class of the records' judgment of a test run (`Deviations.judge`, one function for every driver; the same cases
# in tests/reference-test-verb.sh and tests/mill-test-verb.sh), each over beta's blocked record, judged and recorded:
# a new build error of a configuration of no project of tests.json's (gamma) fails; an executed failure after the last
# summary, with the run's events missing, or in them (a run's outcomes are its events, never its report's lines),
# fails.
judged_and_recorded() {
  local what=$1
  cp "$work/blocked/deviations.json" "$work/deviations.kept"
  verb "$work/blocked"
  local code=$?
  verb "$work/blocked" record
  local code2=$?
  if [ $code != 0 ] && [ $code2 != 0 ] && cmp -s "$work/blocked/deviations.json" "$work/deviations.kept" && grep -q "$2" "$work/verb.log"; then pass=$((pass + 1)); else
    echo "FAIL $what: exits $code and $code2, or the record changed, or no \"$2\": $(tail -3 "$work/verb.log")"; fail=$((fail + 1)); fi
}
echo 1 > "$work/exit"
{ printf '%s\n' "$blocked_run"; printf '%s\n' 'gamma/NewTest.scala:9:1: error: Not found: n' 'n' '^' 'gamma/test: 1 error'; } | transcript
judged_and_recorded "a new build error of no project of tests.json's" "^  gamma/test gamma/NewTest.scala:9:1: error: Not found: n$"
{ printf '%s\n' "$blocked_run"; echo '[fail] lila.b.ThreeTest renders: java.lang.Error: newly executed failure'; } | transcript
touch "$work/no-events"
judged_and_recorded "an executed failure after the last summary, no events" "it wrote no events"
rm -f "$work/no-events"
