x
^
beta/test: 1 error'
printf '%s\n' "$blocked_run" | transcript
echo 1 > "$work/exit"
verb "$work/blocked"
expect "a project blocked, over deviations of none" fail "$work/blocked"
rm -f "$work/blocked/deviations.json"
verb "$work/blocked" baseline
expect "a project blocked, over its own baseline" pass "$work/blocked"
grep -q -F '"beta: blocked by beta/test modules/b/B.scala:1:1: error: Not found: x\nx\n^"' "$work/blocked/deviations.json" && [ "$(grep -c '"beta: ' "$work/blocked/deviations.json")" = 1 ] && pass=$((pass + 1)) ||
  { echo "FAIL the blocked project is not its build's error: $(grep beta "$work/blocked/deviations.json")"; fail=$((fail + 1)); }
printf '%s\n' "$recorded" | sed 's/^\[success\] lila.b.ThreeTest renders$/[fail] lila.b.ThreeTest renders: java.lang.AssertionError: boom/' | transcript
expect "the blocked project run, its case failing" fail "$work/blocked"
rm -f "$work/exit"
printf '%s\n' "$recorded" | transcript
verb "$work/blocked"
grep -q "gone 1 of the record's 1" "$work/verb.log" && pass=$((pass + 1)) || { echo "FAIL the blocked project run as the oracle's: not gone: $(tail -3 "$work/verb.log")"; fail=$((fail + 1)); }
echo 1 > "$work/exit"
printf '%s\n' "$blocked_run" | sed 's/^beta\/test: 1 error$/gamma\/test: 1 error/' | transcript
expect "a project of no summary beside another's failed build" fail "$work/blocked"
grep -q "beta: its suites did not run, and no build of its failed" "$work/verb.log" && pass=$((pass + 1)) || { echo "FAIL another project's build blocked beta: $(tail -3 "$work/verb.log")"; fail=$((fail + 1)); }
# A blocked project's record holds its build's errors as a compile's record does: over the record of beta blocked by
# B.scala:1:1, beta blocked by another error, beta's build counted without its diagnostic, and a project with a note
# of teq's and no failed build, each fail.
echo 1 > "$work/exit"
printf '%s\n' "$blocked_run" | sed 's/^modules\/b\/B.scala:1:1: error: Not found: x$/modules\/b\/B.scala:2:1: error: Not found: y/' | transcript
expect "beta blocked by another error than the record's" fail "$work/blocked"
printf '%s\n' "$blocked_run" | grep -v '^modules/b/B.scala\|^x$\|^\^$' | transcript
expect "beta's build counted without its diagnostic" fail "$work/blocked"
grep -q "beta/test: 1 errors reported without a diagnostic" "$work/verb.log" && pass=$((pass + 1)) || { echo "FAIL a count without its diagnostic blocked beta: $(tail -3 "$work/verb.log")"; fail=$((fail + 1)); }
printf '%s\n' "$blocked_run" | sed '1,4d' | { echo 'teq: alpha/test: generated sources up to date'; cat; } | transcript
expect "a project with a note of teq's and no failed build" fail "$work/blocked"
grep -q "alpha: its suites did not run, and no build of its failed" "$work/verb.log" && pass=$((pass + 1)) || { echo "FAIL a note blocked alpha: $(tail -3 "$work/verb.log")"; fail=$((fail + 1)); }
rm -f "$work/exit"
# A blocked project's allowance covers the cases its build kept from running, never one that ran: over the record of
# beta blocked, beta's case running as an Error before alpha's summary, beta's build's error printed after it, is an
# execution its build's failure contradicts, and fails, judged and recorded.
printf '%s\n' "$blocked_run" > "$work/partial.txt"
