#!/bin/bash
# bench/lila/lila.scala's test verb holds `teq test`'s run to the oracle's inventory: a stand-in teq
# prints a transcript, and the verb passes only where every suite of the inventory ran in its project
# with every case passed, no inventory or an empty one failing at the start
# (tests/support/lila_test_verb.scala). Scenarios: the run as recorded; no inventory; an empty transcript;
# another project's summary alone; a failed case; a missing case; a suite in another project; and the runner's
# pool's transcripts (docs/TOOLING.md, "Tests."): two suites' lines interleaved, among the suites' own output, the
# pool's debug line and a logged error; a case reported twice; a case after its project's summary; a suite whose
# task threw, its error logged and the suite failed, its cases unreported, each held to a deviations.json its
# baseline made empty from the recorded run; a project blocked by its own build, one item of its own a baseline of the
# blocked run records, gone when the project runs as the oracle's, a case of it failing a new item; a project with no
# summary beside another's failed build, which blocks nothing; a real run over the overlays' fallback to one worker, its
# informational note no failure (tests/support/fallback-note); a blocked project's case run as an error, an execution
# its build's failure contradicts; over that record, a new build error of no project of tests.json's and an executed
# failure after the last summary with the events missing or in them, each failing; over an export of alpha's and beta's
# tests and a record of beta's build failing, a run omitting beta failing and beta with nothing to run passing, its
# item gone, a diagnostic before beta's end with nothing run failing, beta's test framework not loading beside alpha's known error and beta's summary counting a failure no
# outcome or event shows each failing, judged and recorded, and beta's tests typed by alpha's failing resident (a
# test->test dependency) ended by its failure, typed by none failing; a run blocked by its build only with
# `teq run`'s exit of 1, still running at the
# readiness deadline or dying by a signal failing over that record (tests/support/lila_run_verb.scala); over a record of
# a failing case, the case an error now
# (the statuses the run's events', tests/support/lila_events.py), not run, failing twice or pending each a new item,
# passing gone; a passing test printing a diagnostic or a line of teq's before its run's summary passing over a record
# of none and over the failing case's, its run without the summary failing, and over a record of a known build error
# and the failing case, a new error on teq's stderr without its count before the cases' passing failing; every case as
# recorded with an exit of 1, judged and
# recorded against a record of none, failing and recording nothing. And the compile verb held to its records
# (tests/support/lila_compile_verb.scala): a killed run recording nothing, a baseline and a run within it, a new error
# failing and its --record leaving the record as it was; generated bytes held by their digest, other bytes failing
# until a migration and failing again after it when they move once more; a --baseline over the record after the
# generated bytes moved, and a --record over two runs (an improvement, then a new error), each changing nothing; the
# coverage a compile owes from the export (two projects with sources), a run of one refused as a baseline and failing
# a judgment, one covering both through the configuration that builds on them recorded, and none covering a
# configuration that is not transitive, one a project's selection of its sources leaves out, one of another platform
# or one whose sources come through its description alone; over a blocked project's record, another error, a count without its diagnostic and a note blocking nothing;
# two
# runs whose first writes other generated bytes and whose second writes the record's failing, judged or recorded.
cd "$(dirname "$0")/.."
TEQ=${TEQ:-./target/release/teq}
work=$(mktemp -d)
trap 'rm -rf "$work"' EXIT
pass=0
fail=0
mkdir -p "$work/here" "$work/empty" "$work/checkout/target/teq" "$work/out"
: > "$work/checkout/target/teq/teq.lock"
cat > "$work/here/tests.json" <<'JSON'
{
 "suites_count": 3,
 "cases_count": 4,
 "suites": {
  "lila.a.OneTest": { "project": "alpha", "cases": [ "adds", "subtracts: twice" ] },
  "lila.a.TwoTest": { "project": "alpha", "cases": [ "parses" ] },
  "lila.b.ThreeTest": { "project": "beta", "cases": [ "renders" ] }
 }
}
JSON
# The transcript the stand-in prints, then the stand-in.
# The stand-in prints the transcript, its summaries counted as teq's tally counts them (tests/support/tally_summaries.py;
# as written where $work/raw is there) on teq's two channels (tests/support/teq_channels.py: teq's own lines on stderr, a
# line `1> ...` a suite's printing on stdout), writes the run's events where --events names (tests/support/lila_events.py: the
# transcript's outcomes by the projects their summaries name, `[fail]` a Failure; events-override.txt in their place
# where it is there, an Error among them), and exits as $work/exit says (0 without it).
transcript() {
  cat > "$work/transcript.txt"
  cat > "$work/teq" <<SH
#!/bin/sh
if [ "\$1" = test ]; then
  [ "\$3" != --events ] || [ -e $work/no-events ] || python3 $PWD/tests/support/lila_events.py $work > "\$4"
  records=; [ "\$5" != --diagnostics ] || [ -e $work/no-diagnostics ] || records="--records \$6"
  { if [ -e $work/raw ]; then cat $work/transcript.txt; else python3 $PWD/tests/support/tally_summaries.py $work/transcript.txt; fi; } | python3 $PWD/tests/support/teq_channels.py \$records
  exit \$(cat $work/exit 2> /dev/null || echo 0)
fi
exit 0
SH
  chmod +x "$work/teq"
}
verb() {
  local here=$1
  timeout 120 "$TEQ" interp tests/support/lila_test_verb.scala --main lilaTestVerb -- "$here" "$work/checkout" "$work/out" "$work/teq" $2 > "$work/verb.log" 2>&1
}
# cexpect <what> <pass|fail> <exit>: a verb's exit as expected.
cexpect() {
  local what=$1 want=$2 code=$3
  if { [ "$want" = pass ] && [ $code = 0 ]; } || { [ "$want" = fail ] && [ $code != 0 ]; }; then
    pass=$((pass + 1))
  else
    echo "FAIL $what: expected the verb to $want, exit $code: $(tail -5 "$work/verb.log")"
    fail=$((fail + 1))
  fi
}
expect() {
  local what=$1 want=$2 here=${3:-$work/here}
  verb "$here"
  local code=$?
  if { [ "$want" = pass ] && [ $code = 0 ]; } || { [ "$want" = fail ] && [ $code != 0 ]; }; then
    pass=$((pass + 1))
  else
    echo "FAIL $what: expected the verb to $want, exit $code: $(tail -5 "$work/verb.log")"
    fail=$((fail + 1))
  fi
}
recorded='[success] lila.a.OneTest adds
