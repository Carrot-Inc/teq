// java.math on JavaScript: BigInteger and BigDecimal arithmetic, text forms, hashes and
// rounding as the JDK has them.
package javamath

import java.math.{BigDecimal, BigInteger, MathContext, RoundingMode}

@main def main(): Unit =
  val a = new BigInteger("123456789012345678901234567890")
  val b = BigInteger.valueOf(-987654321L)
  println(a.add(b))
  println(a.subtract(b))
  println(a.multiply(b))
  println(a.divide(b))
  println(a.remainder(b))
  println(a.mod(BigInteger.valueOf(97)))
  println(b.pow(3))
  println(a.gcd(BigInteger.valueOf(30)))
  println(a.toString(16))
  println(b.toString(2))
  println(a.hashCode)
  println(b.hashCode)
  println(BigInteger.ZERO.hashCode)
  println(a.bitLength)
  println(a.shiftLeft(3))
  println(b.shiftRight(4))
  println(a.compareTo(b))
  println(a.signum)
  println(b.abs)
  println(a.longValue)
  println(b.intValue)
  println(a.testBit(1))
  val x = new BigDecimal("1234.5678")
  val y = new BigDecimal("-0.0300")
  println(x.add(y))
  println(x.subtract(y))
  println(x.multiply(y))
  println(x.divide(new BigDecimal("8")))
  println(x.divide(new BigDecimal("3"), 5, RoundingMode.HALF_UP))
  println(x.divide(new BigDecimal("7"), MathContext.DECIMAL64))
  println(y.scale)
  println(y.precision)
  println(y.stripTrailingZeros)
  println(x.setScale(2, RoundingMode.HALF_EVEN))
  println(new BigDecimal("2.5").setScale(0, RoundingMode.HALF_EVEN))
  println(new BigDecimal("3.5").setScale(0, RoundingMode.HALF_EVEN))
  println(new BigDecimal("-2.5").setScale(0, RoundingMode.HALF_UP))
  println(new BigDecimal("-2.5").setScale(0, RoundingMode.HALF_DOWN))
  println(new BigDecimal("2.1").setScale(0, RoundingMode.CEILING))
  println(new BigDecimal("-2.1").setScale(0, RoundingMode.FLOOR))
  println(new BigDecimal("2.9").setScale(0, RoundingMode.DOWN))
  println(new BigDecimal("2.1").setScale(0, RoundingMode.UP))
  println(x.round(new MathContext(3)))
  println(new BigDecimal("1E+5"))
  println(new BigDecimal("0.000000123"))
  println(new BigDecimal("1E+5").toPlainString)
  println(new BigDecimal("12345678901234567890.5").toBigInteger)
  println(x.hashCode)
  println(y.hashCode)
  println(new BigDecimal("2.0") == new BigDecimal("2.00"))
  println(new BigDecimal("2.0").compareTo(new BigDecimal("2.00")))
  println(BigDecimal.valueOf(0.1))
  println(BigDecimal.valueOf(12345L, 3))
  println(x.doubleValue)
  println(x.negate.movePointLeft(2))
  println(x.movePointRight(6))
  println(x.remainder(new BigDecimal("100")))
