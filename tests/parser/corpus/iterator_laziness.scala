// Iterator.++ takes its suffix by name and chains flat; scanLeft, span, sliding and grouped
// pull from the source as they go.
@main def main(): Unit =
  println(Iterator.from(1).map(_ * 2).take(3).toList)
  println(Iterator.from(1).filter(_ % 2 == 0).take(2).toList)
  println(Iterator.from(1).flatMap(x => Iterator(x, x)).take(3).toList)
  println(Iterator.from(1).zip(Iterator.from(10)).take(2).toList)
  println(Iterator.from(1).takeWhile(_ < 3).toList)
  println(Iterator.from(1).dropWhile(_ < 3).take(2).toList)
  println(Iterator.from(1).zipWithIndex.take(2).toList)
  val it = List(1).iterator ++ { println("  rhs of ++ evaluated"); Iterator.empty }
  println("  ++ built")
  println(it.next())
  println(it.hasNext)
  println(it.hasNext)
  val it2 = Iterator(1, 2, 3).map: x =>
    println("  map " + x)
    x
  println("  it2 built")
  println(it2.next())
  var flag = true
  def lazily = { flag = false; Iterator(2) }
  val flat = (Iterator(Iterator(1)) ++ Iterator(lazily)).flatten
  println(flag)
  println(flat.toList)
  println(flag)
  println(Iterator.from(1).map(n => n * n).scanLeft(0)(_ + _).take(6).toList)
  println(Iterator(1, 2, 3).scanLeft(0)(_ + _).toList)
  println(Iterator[Int]().scanLeft(0)(_ + _).toList)
  println((1 to 100000).foldLeft(Iterator.empty[Int])((r, _) => r ++ Iterator(1)).sum)
  println((Iterator(1) ++ Iterator(2) ++ Iterator(3)).toList)
  val (a, b) = Iterator(1, 2, 3, 4, 1).span(_ < 3)
  println(b.toList)
  println(a.toList)
  val (c, d) = Iterator(1, 2, 3, 4, 1).span(_ < 3)
  println(c.toList)
  println(d.toList)
  println(Iterator.from(1).span(_ < 3)._1.toList)
  println(Iterator(1, 2, 3).grouped(2).toList)
  println(Iterator.from(1).grouped(2).take(2).toList)
  println(Iterator.from(1).sliding(2).take(2).toList)
  println(Iterator(1, 2, 3, 4, 5, 6, 7).sliding(2, 3).toList)
  println(Iterator(1, 2, 3, 4, 5, 6).sliding(2, 3).toList)
  println(Iterator(1, 2, 3, 4, 5, 6, 7, 8, 9).sliding(2, 4).toList)
  println(Iterator(1, 2, 3, 4).sliding(2, 2).toList)
  println(Iterator(1).sliding(2).toList)
  println(Iterator[Int]().sliding(2).toList)
  println(List(1, 2, 3, 4, 5, 6).sliding(2, 3).toList)
  println(List(1, 2, 3, 4).sliding(3, 2).toList)
  println(List(1, 2, 3, 4, 5).sliding(2, 2).toList)
  println(List(1, 2, 3).sliding(2).toList)
  println(List(1, 2).sliding(3).toList)
  println(List(1, 2, 3, 4, 5).grouped(2).toList)
  println(Vector(1, 2, 3, 4, 5, 6, 7, 8).sliding(2, 3).toList)
  println(List(1).iterator ++ { println("  never"); Iterator.empty })
