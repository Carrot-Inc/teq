def pair[A](a: A, b: A): (A, A) = (a, b)

@main def main(): Unit =
  val fs: List[Int => Int] = List(x => x + 1, x => x * 2)
  println(fs.map(_(3)))
  val vs: Vector[Int => Int] = Vector(_ + 1)
  println(vs.map(_(3)))
  val pf: List[PartialFunction[Int, Int]] = List({ case 1 => 10 })
  println(pf.head.isDefinedAt(1))
  val fo: Option[Int => Int] = Some(_ + 1)
  println(fo.map(_(4)))
  val inc = (x: Int) => x + 1
  val both = List(inc, x => x * 2)
  println(both.map(_(3)))
  val p = pair(inc, x => x - 1)
  println(p._2(3))
  val ws: List[(Int, String) => String] = List((a, b) => b * a, (a, _) => a.toString)
  println(ws.map(_(2, "ab")))
  val handlers: Map[String, Int => Unit] = Map("a" -> (x => println(x)), "b" -> (x => println(x * 2)))
  handlers("b")(4)
  val e: Either[String, Int => Int] = Right(_ + 5)
  println(e.map(_(1)))
  val mixed: List[(Int => Int) | String] = List(_ + 1, "s")
  println(mixed.size)
