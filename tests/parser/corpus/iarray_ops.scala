// IArray's operations: construction, access, transformation and folding.
package iarrayops

@main def main(): Unit =
  val xs = IArray(3, 1, 4, 1, 5)
  println(xs.length)
  println(xs(2))
  println(xs.head)
  println(xs.last)
  println(xs.map(_ * 2).mkString(","))
  println(xs.filter(_ > 1).mkString(","))
  println(xs.find(_ > 3))
  println(xs.exists(_ == 5))
  println(xs.forall(_ > 0))
  println(xs.count(_ == 1))
  println(xs.indexOf(4))
  println(xs.slice(1, 3).mkString("[", " ", "]"))
  println(xs.take(2).mkString(","))
  println(xs.drop(3).mkString(","))
  println(xs.reverse.mkString(","))
  println(xs.zipWithIndex.map((x, i) => x * i).mkString(","))
  println(xs.foldLeft(0)(_ + _))
  println(xs.sorted.mkString(","))
  println(xs.distinct.mkString(","))
  println((xs ++ IArray(9)).mkString(","))
  println(xs.toList)
  val names = IArray.from(List("b", "a"))
  println(names.sorted.toList)
  println(IArray.fill(3)("x").mkString)
  println(IArray.tabulate(4)(i => i * i).mkString(","))
  println(IArray.empty[Int].isEmpty)
  println(IArray.genericWrapArray(xs).toList.sum)
  println(xs.collectFirst { case x if x > 3 => x * 10 })
