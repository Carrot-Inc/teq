final case class Item(id: Int, name: String)

def show[A](label: String, value: A): Unit = println(label + ": " + value.toString)

@main def main(): Unit =
  val xs = List(3, 1, 4, 1, 5, 9, 2, 6)
  val v = Vector(3, 1, 4, 1, 5)
  val items = List(Item(1, "b"), Item(2, "a"), Item(3, "b"))

  show("filterNot", xs.filterNot(_ > 3))
  show("partition", xs.partition(_ % 2 == 0))
  show("span", xs.span(_ != 4))
  show("splitAt", xs.splitAt(3))
  show("splitAt big", xs.splitAt(30))
  show("takeRight", xs.takeRight(3))
  show("dropRight", xs.dropRight(3))
  show("takeRight big", xs.takeRight(20))
  show("dropRight neg", xs.dropRight(-1))
  show("slice", xs.slice(2, 5))
  show("slice neg", xs.slice(-2, 2))
  show("init", xs.init)
  show("tail", v.tail)
  show("vector init", v.init)
  show("lift", (xs.lift(2), xs.lift(20), xs.lift(-1)))
  show("patch", xs.patch(2, List(0, 0), 3))
  show("patch insert", xs.patch(1, List(7), 0))
  show("patch end", v.patch(10, Vector(8), 2))
  show("updated", xs.updated(0, 100))
  show("appended", xs.appended(7))
  show("prepended", xs.prepended(7))
  show("appendedAll", xs.appendedAll(Vector(7, 8)))
  show("prependedAll", xs.prependedAll(Some(0)))
  show(":++", v :++ List(1))
  show("++:", List(0) ++: v)
  show("padTo", v.padTo(7, 0))
  show("distinct", xs.distinct)
  show("distinctBy", items.distinctBy(_.name))
  show("indexWhere", (xs.indexWhere(_ > 3), xs.indexWhere(_ > 3, 3), xs.indexWhere(_ > 100)))
  show("indexOf", (xs.indexOf(1), xs.indexOf(1, 2), xs.indexOf(42)))
  show("lastIndexOf", (xs.lastIndexOf(1), xs.lastIndexWhere(_ > 4)))
  show("findLast", (xs.findLast(_ < 3), xs.findLast(_ > 100)))
  show("maxByOption", (items.maxByOption(_.id), List.empty[Item].maxByOption(_.id)))
  show("minByOption", items.minByOption(_.name))
  show("maxOption", (xs.maxOption, List.empty[Int].maxOption, v.minOption))
  show("sum/product", (xs.sum, v.product, List.empty[Int].sum))
  show("min/max", (xs.min, xs.max, v.minBy(x => -x), v.maxBy(x => -x)))
  show("reduceOption", (xs.reduceOption(_ + _), List.empty[Int].reduceOption(_ + _)))
  show("reduceLeft", xs.reduceLeft(_ - _))
  show("foldRight", xs.foldRight("")((x, acc) => acc + x.toString))
  show("fold", xs.fold(0)(_ + _))
  show("scanLeft", xs.scanLeft(0)(_ + _))
  show("zip option", xs.zip(Some("a")))
  show("zip vector", xs.zip(Vector("a", "b", "c")))
  show("vector zip list", v.zip(List("x", "y")))
  show("zipAll", List(1, 2).zipAll(List("a"), 0, "z"))
  show("unzip", List((1, "a"), (2, "b")).unzip)
  show("vector unzip", Vector((1, "a"), (2, "b")).unzip)
  show("unzip3", List((1, "a", true), (2, "b", false)).unzip3)
  show("flatten lists", List(List(1), Nil, List(2, 3)).flatten)
  show("flatten options", List(Some(1), None, Some(3)).flatten)
  show("flatten vector", Vector(List(1), List(2)).flatten)
  show("flatten seq of options", Seq(Some("a"), None, Some("b")).flatten.mkString("&"))
  show("flatMap option", xs.flatMap(x => if x > 3 then Some(x * 2) else None))
  show("flatMap vector", xs.take(2).flatMap(x => Vector(x, x)))
  show("flatMap set", v.flatMap(x => Set(x)))
  show("++ option", xs.take(2) ++ Some(7) ++ None)
  show("++ vector", List(1) ++ Vector(2) ++ Set(3))
  show("vector ++ list", Vector(1) ++ List(2))
  show("concat", List(1).concat(List(2)))
  show("for with option",
    for
      x <- List(1, 2, 3)
      y <- Some(x * 10)
    yield x + y)
  show("grouped", xs.grouped(3).toList)
  show("sliding", xs.sliding(3).toList)
  show("sliding step", xs.sliding(3, 2).toList)
  show("sliding short", List(1, 2).sliding(3).toList)
  show("groupBy", items.groupBy(_.name).toList.sortBy(_._1))
  show("groupMap", items.groupMap(_.name)(_.id).toList.sortBy(_._1))
  show("groupMapReduce", items.groupMapReduce(_.name)(_.id)(_ + _).toList.sortBy(_._1))
  show("vector groupBy", v.groupBy(_ % 2).toList.sortBy(_._1))
  show("partitionMap", xs.partitionMap[Int, String](x => if x % 2 == 0 then Left(x) else Right(x.toString)))
  show("sortBy", items.sortBy(_.name))
  show("sortWith", xs.sortWith(_ > _))
  show("sorted reverse", xs.sorted(using summon[Ordering[Int]].reverse))
  show("vector sortBy", v.sortBy(x => -x))
  show("corresponds", (xs.corresponds(xs.map(_ + 1))(_ < _), xs.corresponds(List(1))(_ == _)))
  show("sameElements", (xs.sameElements(xs.toVector), xs.sameElements(v)))
  show("startsWith", (xs.startsWith(List(3, 1)), xs.startsWith(List(1, 4), 1), xs.endsWith(List(2, 6)), xs.endsWith(List(2))))
  show("diff", xs.diff(List(1, 9, 9)))
  show("intersect", xs.intersect(List(1, 1, 1, 6, 7)))
  show("sizeIs", (xs.sizeIs > 3, xs.sizeIs == 8, xs.lengthIs < 2, xs.lengthCompare(8)))
  show("isDefinedAt", (xs.isDefinedAt(7), xs.isDefinedAt(8), v.indices.toList))
  show("contains", (xs.contains(9), v.contains(7)))
  show("count", (xs.count(_ > 2), v.count(_ == 1)))
  show("find", (v.find(_ > 3), v.find(_ > 30)))
  show("tapEach", xs.take(2).tapEach(x => println("tap " + x.toString)))
  show("view", xs.view.map(_ + 1).filter(_ > 4).toList)
  show("reverseIterator", xs.reverseIterator.take(2).toList)
  show("toSeq", (xs.toSeq, v.toSeq, v.toIndexedSeq, xs.toVector, v.toList))
  show("toSet", xs.take(3).toSet)
  show("toMap", items.map(i => i.id -> i.name).toMap)
  show("toArray", xs.toArray.length)
  show("headOption", (v.headOption, Vector.empty[Int].lastOption, xs.last))
  show("mkString", (xs.mkString, xs.mkString("-"), v.mkString("[", ",", "]")))

  val s: Seq[Int] = Seq(5, 3, 8)
  show("Seq", s)
  show("Seq ops", (s.map(_ + 1), s.filter(_ > 3), s.sorted, s.reverse))
  show("Seq access", (s.headOption, s.length, s(1)))
  show("Seq zipWithIndex", s.zipWithIndex)
  show("Seq.empty", (Seq.empty[Int], Seq.fill(2)("x"), Seq.tabulate(3)(_ * 2)))
  val is: IndexedSeq[Int] = IndexedSeq(1, 2, 3)
  show("IndexedSeq", (is, is.map(_ * 2), is.updated(1, 9)))
  val it: Iterable[Int] = Iterable(1, 2, 3)
  show("Iterable", (it, it.map(_ + 1), it.filter(_ > 1)))
  show("Iterable consumers", (it.sum, it.toList, it.size))

  show("List.from", (List.from(Vector(1, 2)), List.from(Some(1)), List.from(Set(1))))
  show("Vector.from", (Vector.from(List(1, 2)), Vector.from(None)))
  show("List.range", (List.range(0, 10, 3), List.range(5, 0, -2), List.range(1, 1)))
  show("List.iterate", List.iterate(1, 5)(_ * 2))
  show("List.unfold", List.unfold(1)(s => if s > 50 then None else Some((s, s * 3))))
  show("List.concat", List.concat(List(1), Vector(2), Some(3)))
  show("List.fill", List.fill(3)("ab"))

  def total(xs: Int*): Int = xs.sum
  def describe(xs: String*): String = xs.map(_.toUpperCase).mkString(",") + xs.length.toString + xs.headOption.toString
  show("varargs", (total(1, 2, 3), total(), describe("a", "b"), describe(List("x")*)))

  val r = 1 to 5
  show("range", (r.map(_ * 2), r.filter(_ % 2 == 1), r.sum))
  show("range access", (r.toList, r.contains(3), r.size))
  show("range ops", (r.zipWithIndex, r.foldLeft(0)(_ - _), (0 until 10 by 3).toList, (5 to 1 by -2).toVector))
  show("range more", (r.take(2).toList, r.drop(3).toList, r.reverse.toList))
  show("range elements", (r.head, r.last, r(2), r.exists(_ > 4), r.forall(_ > 1)))
  show("range flatMap", r.flatMap(i => List.fill(i % 3)(i)))
  show("range mkString", ((0 to 9) ++ ('a' to 'e') ++ ('X' to 'Z')).mkString)
  show("char range", (('a' to 'e').toList, ('a' until 'c').mkString("|")))
  show("range for", for i <- 1 to 3; j <- i to 3 yield i * j)
  show("range toString", (1 to 5, 0 until 5, 0 until 10 by 3, 0 until 9 by 3, 5 to 1 by -1))
  show("range empty", (5 until 5, 3 to 1, (1 to 3).reverse, (0 until 10 by 3).reverse))
  show("range equals", ((1 to 3) == (1 until 4), (1 to 3).length, (3 to 1).length, (10 to 1 by -3).toList))
  val long1 = List.range(0, 200000)
  val long2 = List.range(0, 200000)
  show("long lists", List[Any](long1 == long2, long1 == long2.updated(199999, 0), long1.hashCode == long2.hashCode, Set(long1).contains(long2), Map(long1 -> 1).get(long2)))
  show("seq equality", List[Any](List(1, 2) == Vector(1, 2), Vector(1, 2) == List(1, 2), List(1, 2) == Seq(1, 2), (1 to 3) == List(1, 2, 3), List(1, 2, 3) == (1 until 4), Nil == Vector.empty[Int], List(1) == Vector(2)))
  show("seq hash", List[Any](List(1, 2).hashCode == Vector(1, 2).hashCode, Set[Seq[Int]](List(1, 2), Vector(1, 2)).size, scala.collection.mutable.ArrayBuffer(1, 2) == List(1, 2), List(Some(1)) == Vector(Some(1))))

  show("tails", List[Any](List(1, 2, 3).tails.toList, List(1, 2, 3).inits.toList, Vector(1, 2).tails.toList, List.empty[Int].tails.toList))
  show("right folds", List[Any](List(1, 2, 3).reduceRight(_ - _), List(1, 2, 3).reduceRightOption(_ - _), List.empty[Int].reduceRightOption(_ - _), List(1, 2, 3).scanRight(0)(_ + _), Vector(1, 2).scanRight(10)(_ + _)))
  show("transpose", List[Any](List(List(1, 2), List(3, 4)).transpose, Vector(List(1, 2, 3), List(4, 5, 6)).transpose, List.empty[List[Int]].transpose))
