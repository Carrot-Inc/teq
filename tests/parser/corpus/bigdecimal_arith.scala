// scala.math.BigDecimal arithmetic: the operators under the DECIMAL128 context, setScale with each
// rounding mode, other contexts' precision, quot and remainder, pow, and divisions that do not
// terminate.
package bigdecimalarith

import java.math.MathContext
import scala.math.BigDecimal.RoundingMode

@main def main(): Unit =
  val a = BigDecimal("12.345")
  val b = BigDecimal("-0.5")
  println(a + b)
  println(a - b)
  println(a * b)
  println(a / b)
  println(a % b)
  println(a quot b)
  println(a remainder b)
  println(a /% BigDecimal(5))
  println(-a)
  println(b.abs)
  println(a.signum + " " + b.signum + " " + BigDecimal(0).signum)
  println(s"${a.sign} ${b.sign}")
  println(a min b)
  println(a max b)
  println(a.pow(3))
  println(b.pow(0))
  println(BigDecimal("1.1").pow(40))
  println(BigDecimal(1) / BigDecimal(3))
  println(BigDecimal(2) / BigDecimal(3))
  println(BigDecimal(-2) / BigDecimal(3))
  println(BigDecimal(10) / BigDecimal(4))
  println(BigDecimal("1.00") / BigDecimal("0.25"))
  println(BigDecimal(1) / BigDecimal(7) * BigDecimal(7))
  println(BigDecimal("100") / BigDecimal("1E+1"))
  println(BigDecimal("7.5") % BigDecimal(2))
  println(BigDecimal("-7.5") % BigDecimal(2))
  println(BigDecimal("7.5") quot BigDecimal("-2"))
  println(BigDecimal("123456789.123456789") quot BigDecimal("0.001"))
  println(BigDecimal("1E+5") quot BigDecimal(3))
  println(BigDecimal("0.0001") remainder BigDecimal("0.00003"))
  println(a < b)
  println(a > b)
  println(a <= a)
  println(a >= BigDecimal("12.3450"))
  println(a compare b)
  println(a == BigDecimal("12.3450"))
  println(a.equals(BigDecimal("12.3450")))
  for mode <- List(RoundingMode.UP, RoundingMode.DOWN, RoundingMode.CEILING, RoundingMode.FLOOR,
      RoundingMode.HALF_UP, RoundingMode.HALF_DOWN, RoundingMode.HALF_EVEN) do
    val row = List("2.5", "1.5", "-2.5", "-1.55", "1.25", "0.125", "-0.125").map(s => BigDecimal(s).setScale(1, mode))
    println(mode.toString + " " + mode.id + " " + row.mkString(" "))
  println(BigDecimal("1.5").setScale(3))
  println(BigDecimal("1.50").setScale(1))
  println(BigDecimal("12345.6789").setScale(-2, RoundingMode.HALF_UP))
  try println(BigDecimal("1.55").setScale(1))
  catch case e: ArithmeticException => println("ArithmeticException: " + e.getMessage)
  try println(BigDecimal("1.55").setScale(1, RoundingMode.UNNECESSARY))
  catch case e: ArithmeticException => println("ArithmeticException: " + e.getMessage)
  try println(BigDecimal(1) / BigDecimal(0))
  catch case e: ArithmeticException => println("ArithmeticException: " + e.getMessage)
  try println(BigDecimal(0) / BigDecimal(0))
  catch case e: ArithmeticException => println("ArithmeticException: " + e.getMessage)
  val mc = new MathContext(5)
  val c = BigDecimal("3.14159265358979", mc)
  println(c)
  println(c.mc)
  println(BigDecimal(2, mc) / BigDecimal(3, mc))
  println((BigDecimal(1, mc) / BigDecimal(3, mc)).precision)
  println(BigDecimal("123.456789", new MathContext(4, java.math.RoundingMode.DOWN)))
  println(BigDecimal("98765.4321").round(new MathContext(3)))
  println(BigDecimal("98765.4321")(new MathContext(2)))
  println(BigDecimal("0.000123456").precision + " " + BigDecimal("0.000123456").scale)
  println(BigDecimal("1234.5").precision + " " + BigDecimal("1234.5").scale)
  println(BigDecimal("1.23E+10").scale)
  println(BigDecimal("1.23E+10").toBigInt)
  println(BigDecimal(1).mc)
  println(BigDecimal.defaultMathContext)
  val long = BigDecimal("1.234567890123456789012345678901234567890")
  println(long)
  println(long.mc)
  println(long + BigDecimal(1))
  println(BigDecimal("0.1") + BigDecimal("0.2"))
  println(BigDecimal(0.1) + BigDecimal(0.2))
  println(BigDecimal("1E-10") * BigDecimal("1E-10"))
  println(BigDecimal("0.00000001"))
  println(BigDecimal("-1E+3").ulp)
  println(BigDecimal("9.99").rounded)
  println(BigDecimal(22) / BigDecimal(7))
  println((BigDecimal(1) / BigDecimal(3)).setScale(4, RoundingMode.HALF_UP))
  println(BigDecimal("12.3456") * 2)
  println(BigDecimal("12.3456") / 2)
  println(BigDecimal("12.3456") + 1.5)
  println(BigDecimal("12.3456") - 1L)
  println(RoundingMode.withName("HALF_EVEN") == RoundingMode.HALF_EVEN)
  println(RoundingMode(4))
