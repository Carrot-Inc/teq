// The routes of java.io.PrintStream's entry points under a redirection, against scalac: Console.withErr, then after it, before Console's first use. Every entry point (Predef's
// print, println(x), println(); Console's three; Console.out's and System.out's print and println of a text, null as String and as
// Any, a char array as itself and as Any) and the err side (which stream Console.err and System.err are, and the calls into a
// logging stream) in each phase; a logging subclass records the overload and the argument it received; each call's line goes
// through the original System.out. The expected lines are scalac's on the JDK (calls whose text carries an array's hash left out).
import java.io.{ByteArrayOutputStream, PrintStream}

class Log(val name: String) extends PrintStream(new ByteArrayOutputStream(), true):
  private def d(x: Any): String = x match
    case null => "null"
    case s: String => "S'" + s + "'"
    case a: Array[Char @unchecked] => "C'" + new String(a) + "'"
    case o => "O'" + o + "'"
  private def note(s: String): Unit = M.log.append(name).append('.').append(s).append(';')
  override def print(s: String): Unit = note("print(String " + d(s) + ")")
  override def print(x: Any): Unit = note("print(Object " + d(x) + ")")
  override def print(a: Array[Char]): Unit = note("print(char[] " + d(a) + ")")
  override def println(): Unit = note("println()")
  override def println(s: String): Unit = note("println(String " + d(s) + ")")
  override def println(x: Any): Unit = note("println(Object " + d(x) + ")")
  override def println(a: Array[Char]): Unit = note("println(char[] " + d(a) + ")")
  override def write(b: Int): Unit = note("write(int)")
  override def write(b: Array[Byte], off: Int, len: Int): Unit = note("write(bytes)")
  override def flush(): Unit = note("flush()")

object M:
