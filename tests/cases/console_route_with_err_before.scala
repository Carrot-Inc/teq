  def done(): Unit =
    orig.println(" log=[" + log.toString + "]")
    log.setLength(0)
  def arr: Array[Char] = Array('a', 'b')
  def who(p: PrintStream): String =
    if p eq orig then "orig" else if p eq origErr then "origErr" else p match
      case l: Log => l.name
      case _ => "other"
  def phase1(): Unit =
    mark("P1 Predef.print Sempty"); print(""); done()
    mark("P1 Predef.println Sempty"); println(""); done()
    mark("P1 Predef.print St"); print("t"); done()
