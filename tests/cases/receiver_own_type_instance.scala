// The instance a view's or an extension method's using clause gets for its constructor variable comes from the
// receiver: a receiver of `UIO[Unit]` (`Z[Any, Nothing, Unit]`) fixes `F` as `Z[Any, Nothing, *]`, the low
// priority instance's, wherever the member's result is expected as the wider `Task[Unit]` (a lambda's body, a by-name
// argument, a val with a declared type, a return, an `if` branch, a `for`'s generator and its yield), never the
// more specific instance the expected type would admit. Each receiver form, through a view and through an extension.
import scala.language.implicitConversions
final class Z[-R, +E, +A](val a: A):
  def flatMap[R1 <: R, E1 >: E, B](k: A => Z[R1, E1, B]): Z[R1, E1, B] = k(a)
  def map[B](f: A => B): Z[R, E, B] = Z(f(a))
object Z:
  def succeed[A](a: A): Z[Any, Nothing, A] = Z(a)
type RIO[-R, +A] = Z[R, Throwable, A]
type Task[+A] = Z[Any, Throwable, A]
type UIO[+A] = Z[Any, Nothing, A]
trait Applicative[F[_]]:
  def name: String
  def unit: F[Unit]
trait Low:
  given low[R, E]: Applicative[[A] =>> Z[R, E, A]] with
    def name = "monadError"
    def unit = Z(())
object Inst extends Low:
  given high[R]: Applicative[[A] =>> RIO[R, A]] with
    def name = "async"
    def unit = Z(())
final class AppOps[F[_], A](fa: F[A]):
  def viaView(tag: String)(using F: Applicative[F]): F[Unit] = { println(tag + ": " + F.name); F.unit }
implicit def toAppOps[F[_], A](fa: F[A]): AppOps[F, A] = AppOps(fa)
extension [F[_], A](fa: F[A])
  def viaExt(tag: String)(using F: Applicative[F]): F[Unit] = { println(tag + ": " + F.name); F.unit }
