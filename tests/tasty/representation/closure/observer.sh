#!/bin/bash
# tests/tasty/representation/closure/observer.sh <work dir>: landing 1's entries, the Quotes API accessors the observer
# calls (the ruling on dc2a3dfec's pass: the observer observes and decides nothing, so its list is the API it calls).
# Compiles the observer (`observe.scala`, `compiler/Scalac.scala`) and the reflection's probes beside it (`probes.scala`,
# which ask the API and decide nothing) with scalac 3.8.4 and `-Xsemanticdb` up to the
# phase that writes the documents, and writes `entries-observer.txt` from the documents: every symbol of
# `scala.quoted.Quotes` an occurrence or a synthetic refers to, one a line. Each is outside `dotty.tools.dotc`, so
# closure.py lists it as the boundary; a member above it would need a `port` line, which the block's `ports` line
# requires, and the observer has none (README.md, "The observer's list"). Bounded: one JVM, at most 5 minutes.
set -e
work=$(realpath -m "$1")
if [ -z "$1" ]; then echo "usage: observer.sh <work dir> [<out file>]" >&2; exit 2; fi
here=$(cd "$(dirname "$0")" && pwd)
repr=$(cd "$here/.." && pwd)
rm -rf "$work/observer" && mkdir -p "$work/observer/semanticdb" "$work/observer/classes" "$work/observer/cp"
echo '@main def cp(): Unit = ()' > "$work/observer/cp/cp.scala"
cp=$(COURSIER_MODE=offline timeout 300 scala-cli --power compile -S 3.8.4 --jvm system --server=false --offline -q \
  --workspace "$work/observer/cp" --print-class-path "$work/observer/cp/cp.scala" --dep org.scala-lang:scala3-compiler_3:3.8.4 | tail -1)
timeout 300 java -Xss16m -cp "$cp" dotty.tools.dotc.Main -usejavacp -classpath "$cp" -color:never -experimental \
  -Xsemanticdb -semanticdb-target "$work/observer/semanticdb" -sourceroot "$repr" \
  -Ystop-after:extractSemanticDBExtractSemanticInfo -d "$work/observer/classes" \
  "$repr/observe.scala" "$repr/compiler/Scalac.scala" "$repr/probes.scala" > "$work/observer/compile.log" 2>&1 \
  || { echo "observer.sh: scalac failed: $(grep -m3 'Error' "$work/observer/compile.log")" >&2; exit 1; }
# The inventory, by default the committed one; check.sh writes it elsewhere and compares (the pass over 334a43adf).
dest=${2:-$here/entries-observer.txt}
python3 - "$work/observer/semanticdb" "$dest" "$here/../../../semanticdb" "$here" <<'PY'
import os, sys
sys.path.insert(0, sys.argv[3])
sys.path.insert(0, sys.argv[4])
import semanticdb
from closure import synthetic_symbols
root, dest = sys.argv[1], sys.argv[2]
api = set()
for d, _, fs in os.walk(root):
    for f in sorted(fs):
        if f.endswith(".semanticdb"):
            for doc in semanticdb.decode_documents(open(os.path.join(d, f), "rb").read()):
                refs = [o.get("symbol", "") for o in doc.get("occurrences", [])]
                for syn in doc.get("synthetics", []):
                    refs += synthetic_symbols(syn.get("tree", {}))
                api |= {r for r in refs if r.startswith("scala/quoted/Quotes#")}
with open(dest, "w") as out:
    out.write("# Generated by observer.sh from the observer's SemanticDB: every Quotes API accessor observe.scala,\n"
              "# compiler/Scalac.scala and probes.scala refer to. The observer ports nothing of dotty: each entry is the API's, outside\n"
              "# dotty.tools.dotc, the list's boundary; `ports` makes a member reached above it fail the tool unless a\n"
              "# `port` line assigns it (the ruling on dc2a3dfec's pass, finding 6).\n")
    out.write("landing 1 observer\nports\n")
    for s in sorted(api):
        out.write(s + "\n")
print(f"ok observer: {len(api)} Quotes API symbols the observer refers to")
PY
