import scala.language.implicitConversions
class A(val x: Long)
class B(x: Int) extends A(x)
class C(override val x: Long) extends B(1)
class A2(val x: String)
class B2(x: Int)(using Conversion[Int, String]) extends A2(x)
class C2(override val x: String)(using Conversion[Int, String]) extends B2(1)
class A3(val x: Int)
class B3(x: => Int) extends A3(x)
class C3(override val x: Int) extends B3(x)
class B4(x: Int) extends A3(x)
class C4(override val x: Int) extends B4(x)
class A5(val x: Int, val y: Int)
class B5(x: Int, y: Int) extends A5(x, y = y)
class C5(override val x: Int, override val y: Int) extends B5(x, y)
