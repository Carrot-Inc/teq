/*
 * Host names to their ASCII form, behind three functions of the libidn2 C
 * interface (idn2.h).
 *
 * The conversion, for a UTF-8 name:
 *   1. UTS #46 mapping, non-transitional, without the STD3 ASCII rules:
 *      every code point is kept, dropped, replaced or refused by its status
 *      in IdnaMappingTable.txt; the result is normalized to NFC.
 *   2. UTS #46 validity of each label ("xn--" labels are decoded first):
 *      NFC, hyphens, no leading combining mark, statuses.
 *   3. The IDNA2008 lookup of each label (RFC 5891, section 5): a label of
 *      ASCII alone is kept; any other is checked against the derived
 *      property of RFC 5892, the CONTEXTJ rules and the Bidi rule of
 *      RFC 5893, encoded with Punycode (RFC 3492) and decoded back.
 *
 * Nothing here allocates but the returned string, and no input makes a loop
 * run longer than a bound set by MAPPED_MAX: a name of more mapped code points
 * is refused before normalization.
 *
 * The tables of idna_tables.h are generated by bench/idna-tables.scala, and
 * tests/idna.scala holds the conversion to GNU libidn2 2.3.8's answers.
 */
#include <stddef.h>
#include <stdint.h>
#include <stdlib.h>
#include <string.h>

#include "idn2.h"
#include "idna_tables.h"

enum { ST_VALID, ST_IGNORED, ST_MAPPED, ST_DEVIATION, ST_DISALLOWED, ST_STD3_VALID, ST_STD3_MAPPED };
enum { CL_PVALID, CL_CONTEXTJ, CL_CONTEXTO, CL_DISALLOWED, CL_UNASSIGNED };
enum { BD_L, BD_R, BD_AL, BD_AN, BD_EN, BD_ES, BD_CS, BD_ET, BD_ON, BD_BN, BD_NSM, BD_OTHER };
enum { JT_U, JT_C, JT_D, JT_L, JT_R, JT_T };

#define P_STATUS(p) ((p) & 7u)
#define P_CLASS(p) ((p) >> 3 & 7u)
#define P_BIDI(p) ((p) >> 6 & 15u)
#define P_JOIN(p) ((p) >> 10 & 7u)
#define P_MARK(p) ((p) >> 13 & 1u)
#define P_VIRAMA(p) ((p) >> 14 & 1u)

#define MAPPED_MAX 254                    /* code points of a mapped name, as libidn2 2.3.8 */
#define NFC_MAX (MAPPED_MAX * DECOMP_MAX) /* code points of its NFC form */
#define LABEL_MAX 63
#define ASCII_NAME_MAX 254                /* with a final dot; 253 without */

#define LAST_CODE_POINT 0x10FFFFu

/* ---- table lookups ---- */

static unsigned props(uint32_t cp) {
  size_t lo = 0, hi = PROP_RUNS;
  if (cp > LAST_CODE_POINT) return ST_DISALLOWED | CL_DISALLOWED << 3 | BD_OTHER << 6;
  while (hi - lo > 1) {
    size_t mid = lo + (hi - lo) / 2;
    if ((prop_runs[mid] >> 11) <= cp) lo = mid; else hi = mid;
  }
  return prop_values[prop_runs[lo] & 0x7ffu];
}

static unsigned combining_class(uint32_t cp) {
  size_t lo = 0, hi = CCC_RUNS;
  while (hi - lo > 1) {
    size_t mid = lo + (hi - lo) / 2;
    if ((ccc_runs[mid] >> 8) <= cp) lo = mid; else hi = mid;
  }
  return ccc_runs[lo] & 0xffu;
}

static size_t find(const uint32_t *keys, size_t count, uint32_t cp) {
  size_t lo = 0, hi = count;
  while (lo < hi) {
    size_t mid = lo + (hi - lo) / 2;
    if (keys[mid] < cp) lo = mid + 1; else hi = mid;
  }
  return lo < count && keys[lo] == cp ? lo : count;
}

/* The replacement of a mapped code point: its length, and the code points at *to. */
static size_t mapping(uint32_t cp, const uint32_t **to) {
  size_t i = find(map_keys, MAP_COUNT, cp);
  if (i == MAP_COUNT) return 0;
  if (map_vals[i] & 0x80000000u) {
    *to = map_pool + (map_vals[i] & 0xffffu);
    return map_vals[i] >> 16 & 0x7fffu;
  }
  *to = map_vals + i;
  return 1;
}

/* ---- UTF-8 ---- */

/* Decodes one scalar value: the bytes read, 0 for an ill-formed sequence.
   A zero byte ends every test early, so nothing past the terminator is read. */
static size_t utf8_decode(const unsigned char *p, uint32_t *cp) {
  uint32_t c = p[0], v;
  if (c < 0x80) { *cp = c; return 1; }
  if (c < 0xC2) return 0;
  if (c < 0xE0) {
    if ((p[1] & 0xC0) != 0x80) return 0;
    *cp = (c & 0x1F) << 6 | (p[1] & 0x3Fu);
    return 2;
  }
  if (c < 0xF0) {
    if ((p[1] & 0xC0) != 0x80 || (p[2] & 0xC0) != 0x80) return 0;
    v = (c & 0x0F) << 12 | (p[1] & 0x3Fu) << 6 | (p[2] & 0x3Fu);
    if (v < 0x800 || (v >= 0xD800 && v <= 0xDFFF)) return 0;
    *cp = v;
    return 3;
  }
  if (c < 0xF5) {
    if ((p[1] & 0xC0) != 0x80 || (p[2] & 0xC0) != 0x80 || (p[3] & 0xC0) != 0x80) return 0;
    v = (c & 0x07) << 18 | (p[1] & 0x3Fu) << 12 | (p[2] & 0x3Fu) << 6 | (p[3] & 0x3Fu);
    if (v < 0x10000 || v > LAST_CODE_POINT) return 0;
    *cp = v;
    return 4;
  }
  return 0;
}

/* ---- NFC (UAX #15) ---- */

#define HANGUL_S 0xAC00u
#define HANGUL_L 0x1100u
#define HANGUL_V 0x1161u
#define HANGUL_T 0x11A7u
#define HANGUL_LS 19u
#define HANGUL_VS 21u
#define HANGUL_TS 28u
#define HANGUL_SS (HANGUL_LS * HANGUL_VS * HANGUL_TS)

/* The full canonical decomposition of one code point: at most DECOMP_MAX code points. */
static size_t decompose(uint32_t cp, uint32_t *out) {
  size_t i, n;
  if (cp >= HANGUL_S && cp < HANGUL_S + HANGUL_SS) {
    uint32_t s = cp - HANGUL_S;
    out[0] = HANGUL_L + s / (HANGUL_VS * HANGUL_TS);
    out[1] = HANGUL_V + s % (HANGUL_VS * HANGUL_TS) / HANGUL_TS;
    if (s % HANGUL_TS == 0) return 2;
    out[2] = HANGUL_T + s % HANGUL_TS;
    return 3;
  }
  i = find(decomp_keys, DECOMP_COUNT, cp);
  if (i == DECOMP_COUNT) { out[0] = cp; return 1; }
  n = decompose(decomp_first[i], out);
  if (decomp_second[i]) n += decompose(decomp_second[i], out + n);
  return n;
}

static uint32_t compose_pair(uint32_t a, uint32_t b) {
  size_t lo = 0, hi = COMP_COUNT;
  if (a >= HANGUL_L && a < HANGUL_L + HANGUL_LS && b >= HANGUL_V && b < HANGUL_V + HANGUL_VS)
    return HANGUL_S + ((a - HANGUL_L) * HANGUL_VS + (b - HANGUL_V)) * HANGUL_TS;
  if (a >= HANGUL_S && a < HANGUL_S + HANGUL_SS && (a - HANGUL_S) % HANGUL_TS == 0 &&
      b > HANGUL_T && b < HANGUL_T + HANGUL_TS)
    return a + (b - HANGUL_T);
  while (lo < hi) {
    size_t mid = lo + (hi - lo) / 2;
    size_t d = comp_index[mid];
    if (decomp_first[d] < a || (decomp_first[d] == a && decomp_second[d] < b)) lo = mid + 1; else hi = mid;
  }
  if (lo < COMP_COUNT && decomp_first[comp_index[lo]] == a && decomp_second[comp_index[lo]] == b)
    return decomp_keys[comp_index[lo]];
  return 0;
}

/* Normalizes n <= MAPPED_MAX code points into out (room for NFC_MAX); the length of the result. */
static size_t nfc(const uint32_t *in, size_t n, uint32_t *out) {
  unsigned char cc[NFC_MAX];
  size_t m = 0, i, o = 0, starter = 0;
  int have_starter = 0;
  unsigned last = 0; /* class of the last code point kept after the starter; 0: none */

  for (i = 0; i < n; i++) m += decompose(in[i], out + m);
  for (i = 0; i < m; i++) cc[i] = (unsigned char)combining_class(out[i]);
  /* canonical order: a stable sort of every run of non-starters */
  for (i = 1; i < m; i++) {
    size_t j = i;
    uint32_t c = out[i];
    unsigned char k = cc[i];
    if (k == 0) continue;
    while (j > 0 && cc[j - 1] > k) {
      out[j] = out[j - 1];
      cc[j] = cc[j - 1];
      j--;
    }
    out[j] = c;
    cc[j] = k;
  }
  /* composition */
  for (i = 0; i < m; i++) {
    uint32_t c = out[i];
    unsigned k = cc[i];
    if (have_starter && (last == 0 || last < k)) {
      uint32_t composite = compose_pair(out[starter], c);
      if (composite) { out[starter] = composite; continue; }
    }
    if (k == 0) { starter = o; have_starter = 1; last = 0; } else last = k;
    out[o++] = c;
  }
  return o;
}

/* A surrogate (a decoded label may hold a trailing one) is in no normalization form. */
static int is_nfc(const uint32_t *s, size_t n) {
  uint32_t t[LABEL_MAX * DECOMP_MAX];
  size_t i;
  for (i = 0; i < n; i++)
    if (s[i] >= 0xD800 && s[i] <= 0xDFFF) return 0;
  return nfc(s, n, t) == n && memcmp(s, t, n * sizeof *s) == 0;
}

/* ---- Punycode (RFC 3492) ---- */

#define PUNY_BASE 36u
#define PUNY_TMIN 1u
#define PUNY_TMAX 26u
#define PUNY_SKEW 38u
#define PUNY_DAMP 700u
#define PUNY_INITIAL_BIAS 72u
#define PUNY_INITIAL_N 128u

static uint32_t puny_adapt(uint32_t delta, uint32_t points, int first) {
  uint32_t k = 0;
  delta = first ? delta / PUNY_DAMP : delta / 2;
  delta += delta / points;
  while (delta > (PUNY_BASE - PUNY_TMIN) * PUNY_TMAX / 2) {
    delta /= PUNY_BASE - PUNY_TMIN;
    k += PUNY_BASE;
  }
  return k + (PUNY_BASE - PUNY_TMIN + 1) * delta / (delta + PUNY_SKEW);
}

static uint32_t puny_threshold(uint32_t k, uint32_t bias) {
  return k <= bias ? PUNY_TMIN : k >= bias + PUNY_TMAX ? PUNY_TMAX : k - bias;
}

/* A digit's value; '_' reads as zero, as it does in the library this one stands in for. */
static uint32_t puny_digit(uint32_t c) {
  if (c >= '0' && c <= '9') return c - '0' + 26;
  if (c >= 'a' && c <= 'z') return c - 'a';
  if (c >= 'A' && c <= 'Z') return c - 'A';
  if (c == '_') return 0;
  return PUNY_BASE;
}

/* Decodes the part of an A-label after "xn--" into at most LABEL_MAX code points.
   Letters, digits, '-' and '_' are the only input accepted; a result of ASCII
   alone, a code point past U+10FFFF and a leading surrogate are refused. */
static int puny_decode(const uint32_t *in, size_t len, uint32_t *out, size_t *outlen) {
  size_t basic = 0, pos, o, j;
  uint32_t n = PUNY_INITIAL_N, bias = PUNY_INITIAL_BIAS, i = 0;

  for (j = 0; j < len; j++) {
    if (puny_digit(in[j]) == PUNY_BASE && in[j] != '-') return IDN2_PUNYCODE_BAD_INPUT;
    if (in[j] == '-') basic = j;
  }
  pos = basic > 0 ? basic + 1 : 0;
  if (pos >= len) return IDN2_PUNYCODE_BAD_INPUT;
  if (basic >= LABEL_MAX) return IDN2_PUNYCODE_BIG_OUTPUT;
  for (j = 0; j < basic; j++) out[j] = in[j];
  o = basic;
  while (pos < len) {
    uint32_t old = i, w = 1, k;
    for (k = PUNY_BASE;; k += PUNY_BASE) {
      uint32_t digit, t;
      if (pos >= len) return IDN2_PUNYCODE_BAD_INPUT;
      digit = puny_digit(in[pos++]);
      if (digit >= PUNY_BASE) return IDN2_PUNYCODE_BAD_INPUT;
      if (digit > (UINT32_MAX - i) / w) return IDN2_PUNYCODE_OVERFLOW;
      i += digit * w;
      t = puny_threshold(k, bias);
      if (digit < t) break;
      if (w > UINT32_MAX / (PUNY_BASE - t)) return IDN2_PUNYCODE_OVERFLOW;
      w *= PUNY_BASE - t;
    }
    bias = puny_adapt(i - old, (uint32_t)o + 1, old == 0);
    if (i / (o + 1) > UINT32_MAX - n) return IDN2_PUNYCODE_OVERFLOW;
    n += i / (uint32_t)(o + 1);
    i %= (uint32_t)(o + 1);
    if (n > LAST_CODE_POINT || (n >= 0xD800 && n <= 0xDBFF)) return IDN2_PUNYCODE_BAD_INPUT;
    if (o >= LABEL_MAX) return IDN2_PUNYCODE_BIG_OUTPUT;
    memmove(out + i + 1, out + i, (o - i) * sizeof *out);
    out[i++] = n;
    o++;
  }
  *outlen = o;
  return IDN2_OK;
}

/* Encodes a label into at most cap characters (the part after "xn--"). */
static int puny_encode(const uint32_t *in, size_t len, char *out, size_t *outlen, size_t cap) {
  static const char digits[] = "abcdefghijklmnopqrstuvwxyz0123456789";
  uint32_t n = PUNY_INITIAL_N, delta = 0, bias = PUNY_INITIAL_BIAS;
  size_t o = 0, h, basic, j;

  for (j = 0; j < len; j++) {
    if (in[j] < 0x80) {
      if (o >= cap) return IDN2_PUNYCODE_BIG_OUTPUT;
      out[o++] = (char)in[j];
    }
  }
  h = basic = o;
  if (basic > 0) {
    if (o >= cap) return IDN2_PUNYCODE_BIG_OUTPUT;
    out[o++] = '-';
  }
  while (h < len) {
    uint32_t m = UINT32_MAX;
    for (j = 0; j < len; j++)
      if (in[j] >= n && in[j] < m) m = in[j];
    if (m - n > (UINT32_MAX - delta) / (uint32_t)(h + 1)) return IDN2_PUNYCODE_OVERFLOW;
    delta += (m - n) * (uint32_t)(h + 1);
    n = m;
    for (j = 0; j < len; j++) {
      if (in[j] < n && ++delta == 0) return IDN2_PUNYCODE_OVERFLOW;
      if (in[j] == n) {
        uint32_t q = delta, k;
        for (k = PUNY_BASE;; k += PUNY_BASE) {
          uint32_t t = puny_threshold(k, bias);
          if (q < t) break;
          if (o >= cap) return IDN2_PUNYCODE_BIG_OUTPUT;
          out[o++] = digits[t + (q - t) % (PUNY_BASE - t)];
          q = (q - t) / (PUNY_BASE - t);
        }
        if (o >= cap) return IDN2_PUNYCODE_BIG_OUTPUT;
        out[o++] = digits[q];
        bias = puny_adapt(delta, (uint32_t)h + 1, h == basic);
        delta = 0;
        h++;
      }
    }
    delta++;
    n++;
  }
  *outlen = o;
  return IDN2_OK;
}

static int has_ace_prefix(const uint32_t *l, size_t len) {
  return len >= 4 && l[0] == 'x' && l[1] == 'n' && l[2] == '-' && l[3] == '-';
}

/* ---- UTS #46, section 4.1: validity of one label of the mapped name ---- */

/* A Punycode error ends the conversion at once (*fatal); a validity error is
   the answer only if no later label has one. */
static int tr46_label(const uint32_t *l, size_t len, int *fatal) {
  uint32_t decoded[LABEL_MAX];
  size_t i;
  int ace = has_ace_prefix(l, len);

  if (ace) {
    size_t n;
    int rc = puny_decode(l + 4, len - 4, decoded, &n);
    if (rc != IDN2_OK) { *fatal = 1; return rc; }
    l = decoded;
    len = n;
    if (!is_nfc(l, len)) return IDN2_NOT_NFC;
  }
  if (len >= 4 && l[2] == '-' && l[3] == '-') return IDN2_2HYPHEN;
  if (len > 0 && (l[0] == '-' || l[len - 1] == '-')) return IDN2_HYPHEN_STARTEND;
  if (len > 0 && P_MARK(props(l[0]))) return IDN2_LEADING_COMBINING;
  if (ace) {
    for (i = 0; i < len; i++) {
      unsigned st = P_STATUS(props(l[i]));
      if (st != ST_VALID && st != ST_DEVIATION && st != ST_STD3_VALID && st != ST_STD3_MAPPED)
        return IDN2_INVALID_NONTRANSITIONAL;
    }
  }
  return IDN2_OK;
}

/* ---- RFC 5892, appendix A.1 and A.2: ZERO WIDTH NON-JOINER and JOINER ---- */

static int contextj_ok(const uint32_t *l, size_t len, size_t at) {
  size_t j;
  if (at == 0) return 0;
  if (P_VIRAMA(props(l[at - 1]))) return 1;
  if (l[at] != 0x200C) return 0;
  /* (Joining_Type:{L,D})(Joining_Type:T)*‌(Joining_Type:T)*(Joining_Type:{R,D}) */
  for (j = at; j > 0; j--) {
    unsigned jt = P_JOIN(props(l[j - 1]));
    if (jt == JT_T) continue;
    if (jt != JT_L && jt != JT_D) return 0;
    break;
  }
  if (j == 0) return 0;
  for (j = at + 1; j < len; j++) {
    unsigned jt = P_JOIN(props(l[j]));
    if (jt == JT_T) continue;
    return jt == JT_R || jt == JT_D;
  }
  return 0;
}

/* ---- RFC 5893, section 2: the Bidi rule, for a label that holds a right-to-left character ----
   Two departures from the RFC, kept because libidn2 2.3.8 answers so: a label that
   ends in a nonspacing mark passes the test of its end whatever precedes the mark,
   and European and Arabic digits may share a label (rule 4 is not applied). */

static int bidi_ok(const uint32_t *l, size_t len) {
  size_t i;
  unsigned first, last;
  int rtl = 0;

  for (i = 0; i < len; i++) {
    unsigned b = P_BIDI(props(l[i]));
    if (b == BD_R || b == BD_AL || b == BD_AN) rtl = 1;
  }
  if (!rtl) return 1;
  first = P_BIDI(props(l[0]));
  if (first != BD_R && first != BD_AL && first != BD_L) return 0;
  for (i = 0; i < len; i++) {
    unsigned b = P_BIDI(props(l[i]));
    if (b == BD_EN || b == BD_ES || b == BD_CS || b == BD_ET || b == BD_ON || b == BD_BN || b == BD_NSM) continue;
    if (first == BD_L ? b != BD_L : b != BD_R && b != BD_AL && b != BD_AN) return 0;
  }
  last = P_BIDI(props(l[len - 1]));
  if (last == BD_NSM || last == BD_EN) return 1;
  return first == BD_L ? last == BD_L : last == BD_R || last == BD_AL || last == BD_AN;
}

/* ---- RFC 5891, section 5: the lookup form of one label ---- */

static int lookup_label(const uint32_t *l, size_t len, char *out, size_t *outlen) {
  uint32_t decoded[LABEL_MAX], back[LABEL_MAX];
  const uint32_t *u = l;
  size_t ulen = len, i, n;
  int ascii = 1, ace = 0, rc;

  for (i = 0; i < len; i++)
    if (l[i] >= 0x80) ascii = 0;
  if (ascii) {
    if (!has_ace_prefix(l, len)) {
      if (len > LABEL_MAX) return IDN2_TOO_BIG_LABEL;
      for (i = 0; i < len; i++) out[i] = (char)l[i];
      *outlen = len;
      return IDN2_OK;
    }
    rc = puny_decode(l + 4, len - 4, decoded, &ulen);
    if (rc != IDN2_OK) return rc;
    u = decoded;
    ace = 1;
  }

  for (i = 0; i < ulen; i++) {
    unsigned p = props(u[i]);
    /* what UTS #46 lets through without the STD3 rules stays allowed */
    if (P_CLASS(p) == CL_DISALLOWED && P_STATUS(p) != ST_STD3_VALID && P_STATUS(p) != ST_STD3_MAPPED)
      return IDN2_DISALLOWED;
  }
  for (i = 0; i < ulen; i++)
    if (P_CLASS(props(u[i])) == CL_CONTEXTJ && !contextj_ok(u, ulen, i)) return IDN2_CONTEXTJ;
  for (i = 0; i < ulen; i++)
    if (P_CLASS(props(u[i])) == CL_UNASSIGNED) return IDN2_UNASSIGNED;
  if (!bidi_ok(u, ulen)) return IDN2_BIDI;

  memcpy(out, "xn--", 4);
  rc = puny_encode(u, ulen, out + 4, &n, LABEL_MAX - 4);
  if (rc != IDN2_OK) return rc;
  if (ace) {
    if (n + 4 != len) return IDN2_ALABEL_ROUNDTRIP_FAILED;
    for (i = 0; i < len; i++)
      if (l[i] != (unsigned char)out[i]) return IDN2_ALABEL_ROUNDTRIP_FAILED;
  } else {
    uint32_t encoded[LABEL_MAX];
    size_t blen;
    for (i = 0; i < n; i++) encoded[i] = (unsigned char)out[4 + i];
    if (puny_decode(encoded, n, back, &blen) != IDN2_OK || blen != ulen ||
        memcmp(back, u, ulen * sizeof *u) != 0)
      return IDN2_ALABEL_ROUNDTRIP_FAILED;
  }
  *outlen = n + 4;
  return IDN2_OK;
}

/* ---- the interface ---- */

int idn2_to_ascii_8z(const char *input, char **output, int flags) {
  uint32_t name[MAPPED_MAX], norm[NFC_MAX], cp;
  char ascii[ASCII_NAME_MAX + 1], label[LABEL_MAX];
  const unsigned char *p;
  size_t n = 0, m, i, total = 0;
  int too_long = 0, pending = IDN2_OK;

  if (flags & ~(IDN2_NFC_INPUT | IDN2_ALABEL_ROUNDTRIP | IDN2_NONTRANSITIONAL | IDN2_ALLOW_UNASSIGNED))
    return IDN2_INVALID_FLAGS;
  if (input == NULL) {
    if (output) *output = NULL;
    return IDN2_OK;
  }

  for (p = (const unsigned char *)input; *p;) {
    size_t k = utf8_decode(p, &cp);
    if (k == 0) return IDN2_ENCODING_ERROR;
    p += k;
  }

  for (p = (const unsigned char *)input; *p;) {
    const uint32_t *to = &cp;
    size_t k = 1;
    p += utf8_decode(p, &cp);
    switch (P_STATUS(props(cp))) {
      case ST_DISALLOWED: return IDN2_DISALLOWED;
      case ST_IGNORED: k = 0; break;
      case ST_MAPPED:
      case ST_STD3_MAPPED: k = mapping(cp, &to); break;
      default: break;
    }
    for (i = 0; i < k; i++) {
      if (n < MAPPED_MAX) name[n++] = to[i]; else too_long = 1;
    }
  }
  if (too_long) return IDN2_TOO_BIG_DOMAIN;
  m = nfc(name, n, norm);

  for (i = 0;;) {
    size_t j = i;
    int fatal = 0, rc;
    while (j < m && norm[j] != '.') j++;
    rc = tr46_label(norm + i, j - i, &fatal);
    if (fatal) return rc;
    if (rc != IDN2_OK) pending = rc;
    if (j == m) break;
    i = j + 1;
  }
  if (pending != IDN2_OK) return pending;

  for (i = 0;;) {
    size_t j = i, len;
    int rc;
    while (j < m && norm[j] != '.') j++;
    rc = lookup_label(norm + i, j - i, label, &len);
    if (rc != IDN2_OK) return rc;
    /* 253 characters, or 254 with a final dot */
    if (total + len > (len == 0 ? ASCII_NAME_MAX : ASCII_NAME_MAX - 1)) return IDN2_TOO_BIG_DOMAIN;
    memcpy(ascii + total, label, len);
    total += len;
    if (j == m) break;
    if (total + 1 > ASCII_NAME_MAX) return IDN2_TOO_BIG_DOMAIN;
    ascii[total++] = '.';
    i = j + 1;
  }
  ascii[total] = 0;

  if (output) {
    char *copy = malloc(total + 1);
    if (copy == NULL) return IDN2_MALLOC;
    memcpy(copy, ascii, total + 1);
    *output = copy;
  }
  return IDN2_OK;
}

void idn2_free(void *ptr) { free(ptr); }

const char *idn2_strerror(int rc) {
  switch (rc) {
    case IDN2_OK: return "success";
    case IDN2_MALLOC: return "out of memory";
    case IDN2_ENCODING_ERROR: return "host name is not valid UTF-8";
    case IDN2_PUNYCODE_BAD_INPUT: return "host name label has invalid Punycode";
    case IDN2_PUNYCODE_BIG_OUTPUT: return "host name label is too long in Punycode";
    case IDN2_PUNYCODE_OVERFLOW: return "host name label overflows in Punycode";
    case IDN2_TOO_BIG_DOMAIN: return "host name is too long";
    case IDN2_TOO_BIG_LABEL: return "host name label is longer than 63 characters";
    case IDN2_INVALID_FLAGS: return "unsupported conversion flags";
    case IDN2_NOT_NFC: return "host name label is not in Unicode normalization form C";
    case IDN2_2HYPHEN: return "host name label has hyphens in its third and fourth positions";
    case IDN2_HYPHEN_STARTEND: return "host name label starts or ends with a hyphen";
    case IDN2_LEADING_COMBINING: return "host name label starts with a combining mark";
    case IDN2_DISALLOWED: return "host name has a disallowed character";
    case IDN2_CONTEXTJ: return "host name has a joiner character out of context";
    case IDN2_UNASSIGNED: return "host name has an unassigned code point";
    case IDN2_BIDI: return "host name label mixes text directions";
    case IDN2_INVALID_NONTRANSITIONAL: return "host name label decodes to a character that is not valid";
    case IDN2_ALABEL_ROUNDTRIP_FAILED: return "host name label does not survive the Punycode round trip";
    default: return "unknown error";
  }
}
