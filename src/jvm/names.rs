//! JVM names: scalac's `$`-encoding of operator characters, the binary names of classes, and
//! the erased types the backend computes with.

use std::rc::Rc;

/// scalac's NameTransformer: operator characters become `$plus`, `$colon` and so on.
pub fn encode(name: &str) -> String {
    encode_name(name).into_owned()
}

/// scala-library's `NameTransformer.encode`, over the name's UTF-16 code units as it reads them
/// (`charAt`): an operator character is written out, a unit that is no part of a Java identifier
/// (`Character.isJavaIdentifierPart`) becomes `$u` and its code, any other stays.
pub fn encode_name(name: &str) -> std::borrow::Cow<'_, str> {
    if name.bytes().all(|b| b.is_ascii_alphanumeric() || b == b'_' || b == b'$') {
        return std::borrow::Cow::Borrowed(name);
    }
    let mut out = String::with_capacity(name.len() + 8);
    let mut buf = [0u16; 2];
    for ch in name.chars() {
        for &unit in ch.encode_utf16(&mut buf).iter() {
            let op = match unit {
                0x7E => "$tilde",
                0x3D => "$eq",
                0x3C => "$less",
                0x3E => "$greater",
                0x21 => "$bang",
                0x23 => "$hash",
                0x25 => "$percent",
                0x5E => "$up",
                0x26 => "$amp",
                0x7C => "$bar",
                0x2A => "$times",
                0x2F => "$div",
                0x2B => "$plus",
                0x2D => "$minus",
                0x3A => "$colon",
                0x5C => "$bslash",
                0x3F => "$qmark",
                0x40 => "$at",
                _ => "",
            };
            if !op.is_empty() {
                out.push_str(op);
            } else if is_java_identifier_part(unit) {
                // A surrogate is no identifier part: what reaches here is a whole character.
                out.push(char::from_u32(unit as u32).unwrap_or('\u{FFFD}'));
            } else {
                out.push_str(&format!("$u{:04X}", unit));
            }
        }
    }
    std::borrow::Cow::Owned(out)
}

/// `Character.isJavaIdentifierPart(char)`: a letter, a currency symbol, a connecting punctuation,
/// a digit, a numeric letter, a combining or non-spacing mark, or an identifier-ignorable unit
/// (the controls `\u0000`..`\u0008`, `\u000E`..`\u001B`, `\u007F`..`\u009F` and the format
/// characters). The ranges are JDK 21's (Unicode 15.0, the JDK lila pins), generated by asking it
/// for every unit.
pub fn is_java_identifier_part(unit: u16) -> bool {
    JAVA_IDENTIFIER_PART
        .binary_search_by(|&(lo, hi)| {
            if hi < unit {
                std::cmp::Ordering::Less
            } else if lo > unit {
                std::cmp::Ordering::Greater
            } else {
                std::cmp::Ordering::Equal
            }
        })
        .is_ok()
}

